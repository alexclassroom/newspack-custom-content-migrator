<?php
/**
 * Foundation data validation commands for validating exported content from Foundation.
 *
 * @package NewspackCustomContentMigrator
 */

namespace NewspackCustomContentMigrator\Command\General\Foundation;

use Newspack\MigrationTools\Command\WpCliCommandTrait;
use NewspackCustomContentMigrator\Command\RegisterCommandInterface;
use Newspack\MigrationTools\Util\JsonIterator;
use Newspack\MigrationTools\Util\Log\MultiLog;
use WP_CLI;

class FoundationDataValidation implements RegisterCommandInterface {

	use WpCliCommandTrait;

	/**
	 * JSON iterator.
	 *
	 * @var JsonIterator
	 */
	private JsonIterator $json_iterator;

	/**
	 * Logger.
	 *
	 * @var MultiLog
	 */
	private MultiLog $logger;

	/**
	 * Constructor.
	 */
	public function __construct() {
		$this->json_iterator = new JsonIterator();
		$this->logger        = MultiLog::get_cli_and_file_logger( 'foundation-validate-data' );
	}

	/**
	 * {@inheritDoc}
	 */
	public static function register_commands(): void {
		WP_CLI::add_command(
			'newspack-content-migrator foundation-validate-categories',
			self::get_command_closure( 'cmd_validate_categories' ),
			[
				'shortdesc' => 'Validates Foundation categories received from their export.',
				'synopsis'  => [
					[
						'type'        => 'assoc',
						'name'        => 'category-json-file',
						'description' => 'Path to the JSON file containing the categories (e.g. `Category.json`). The JSON file generated by Foundation contains all taxonomies, including categories and tags. despite its name.',
						'optional'    => false,
						'repeating'   => false,
					],
				],
			]
		);

		WP_CLI::add_command(
			'newspack-content-migrator foundation-validate-brands',
			self::get_command_closure( 'cmd_validate_brands' ),
			[
				'shortdesc' => 'Validates Foundation brands received from their export.',
				'synopsis'  => [
					[
						'type'        => 'assoc',
						'name'        => 'post-json-file',
						'description' => 'Path to the JSON file containing the posts (e.g. `Post.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
				],
			]
		);

		WP_CLI::add_command(
			'newspack-content-migrator foundation-validate-users',
			self::get_command_closure( 'cmd_validate_users' ),
			[
				'shortdesc' => 'Validates Foundation users received from their export.',
				'synopsis'  => [
					[
						'type'        => 'assoc',
						'name'        => 'wp-author-json-file',
						'description' => 'Path to the JSON file containing the authors (e.g. `WPAuthor.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
					[
						'type'        => 'assoc',
						'name'        => 'wp-contributor-json-file',
						'description' => 'Path to the JSON file containing the contributors (e.g. `WPContributor.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
					[
						'type'        => 'assoc',
						'name'        => 'wp-editor-json-file',
						'description' => 'Path to the JSON file containing the editors (e.g. `WPEditor.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
					[
						'type'        => 'assoc',
						'name'        => 'wp-comment-author-json-file',
						'description' => 'Path to the JSON file containing the comment authors (e.g. `WPCommentAuthor.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
				],
			]
		);

		WP_CLI::add_command(
			'newspack-content-migrator foundation-validate-content',
			self::get_command_closure( 'cmd_validate_content' ),
			[
				'shortdesc' => 'Validates Foundation content received from their export.',
				'synopsis'  => [
					[
						'type'        => 'assoc',
						'name'        => 'post-json-file',
						'description' => 'Path to the JSON file containing the posts (e.g. `Post.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
					[
						'type'        => 'assoc',
						'name'        => 'page-json-file',
						'description' => 'Path to the JSON file containing the pages (e.g. `Page.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
					[
						'type'        => 'assoc',
						'name'        => 'slideshow-json-file',
						'description' => 'Path to the JSON file containing the slideshows (e.g. `Slideshow.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
					[
						'type'        => 'assoc',
						'name'        => 'comment-json-file',
						'description' => 'Path to the JSON file containing the comments (e.g. `Comment.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
					[
						'type'        => 'assoc',
						'name'        => 'issue-json-file',
						'description' => 'Path to the JSON file containing the issues (e.g. `Issue.json`).',
						'optional'    => false,
						'repeating'   => false,
					],
				],
			]
		);
	}

	/**
	 * Validates Foundation categories received from their export.
	 * Callable for 'newspack-content-migrator foundation-validate-categories' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_validate_categories( array $args, array $assoc_args ): void {
		$category_json_file = $assoc_args['category-json-file'];

		$categories = $this->json_iterator->items( $category_json_file );

		$categories_count = 0;
		$tags_count       = 0;

		foreach ( $categories as $category ) {
			if ( in_array( $category->class, [ 'Category', 'Section', 'Topic' ], true ) ) {
				++$categories_count;
			} elseif ( 'Tag' === $category->class ) {
				++$tags_count;
			} else {
				$this->logger->warning( sprintf( 'Found category with unknown class: %s', $category->class ) );
			}
		}

		$this->logger->info( sprintf( 'Found %d categories and %d tags.', $categories_count, $tags_count ) );
	}

	/**
	 * Validates Foundation brands received from their export.
	 * Callable for 'newspack-content-migrator foundation-validate-brands' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_validate_brands( array $args, array $assoc_args ): void {
		$post_json_file = $assoc_args['post-json-file'];

		$brands = [];
		$posts  = $this->json_iterator->items( $post_json_file );

		foreach ( $posts as $post ) {
			if ( isset( $post->brand ) && ! empty( $post->brand ) && ! in_array( $post->brand, $brands, true ) ) {
				$brands[] = $post->brand;
			}
		}

		$this->logger->info( sprintf( 'Found %d brands.', count( $brands ) ) );

		if ( 0 < count( $brands ) && ! taxonomy_exists( 'brand' ) ) {
			$this->logger->warning( 'Brands found, please ensure that the Newspack Multibranded plugin is installed and activated.' );
		}
	}

	/**
	 * Validates Foundation users received from their export.
	 * Callable for 'newspack-content-migrator foundation-validate-users' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_validate_users( array $args, array $assoc_args ): void {
		$wp_author_json_file         = $assoc_args['wp-author-json-file'];
		$wp_contributor_json_file    = $assoc_args['wp-contributor-json-file'];
		$wp_editor_json_file         = $assoc_args['wp-editor-json-file'];
		$wp_comment_author_json_file = $assoc_args['wp-comment-author-json-file'];

		$authors         = $this->json_iterator->count_json_array_entries( $wp_author_json_file );
		$contributors    = $this->json_iterator->count_json_array_entries( $wp_contributor_json_file );
		$editors         = $this->json_iterator->count_json_array_entries( $wp_editor_json_file );
		$comment_authors = $this->json_iterator->count_json_array_entries( $wp_comment_author_json_file );

		$this->logger->info( sprintf( 'Found %d authors, %d contributors, %d editors and %d comment authors.', $authors, $contributors, $editors, $comment_authors ) );
	}

	/**
	 * Validates Foundation content received from their export.
	 * Callable for 'newspack-content-migrator foundation-validate-content' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_validate_content( array $args, array $assoc_args ): void {
		$post_json_file      = $assoc_args['post-json-file'];
		$page_json_file      = $assoc_args['page-json-file'];
		$slideshow_json_file = $assoc_args['slideshow-json-file'];
		$comment_json_file   = $assoc_args['comment-json-file'];
		$issue_json_file     = $assoc_args['issue-json-file'];

		$posts      = $this->json_iterator->count_json_array_entries( $post_json_file );
		$pages      = $this->json_iterator->count_json_array_entries( $page_json_file );
		$slideshows = $this->json_iterator->count_json_array_entries( $slideshow_json_file );
		$comments   = $this->json_iterator->count_json_array_entries( $comment_json_file );
		$issues     = $this->json_iterator->count_json_array_entries( $issue_json_file );

		$this->logger->info( sprintf( 'Found %d posts, %d pages, %d issues, %d slideshows and %d comments.', $posts, $pages, $issues, $slideshows, $comments ) );
	}
}
