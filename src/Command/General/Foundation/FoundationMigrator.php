				$logger->error( sprintf( 'Slideshow %d not migrated', $slideshow->oid ) );
				continue;
			}

			$related_slideshows = $slideshow->relatedSlideshows;
			if ( empty( $related_slideshows ) ) {
				continue;
			}

			// Check if the slideshow has already migrated related slideshows.
			if ( get_post_meta( $existing_post_id, self::MIGRATED_RELATED_SLIDESHOWS_META_KEY, true ) ) {
				continue;
