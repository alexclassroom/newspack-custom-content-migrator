	/**
	 * Migrates Foundation slideshows received from their export.
	 * Callable for 'newspack-content-migrator foundation-migrate-slideshows' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_migrate_slideshows( array $args, array $assoc_args ): void {
		global $wpdb;

		$logger     = MultiLog::get_cli_and_file_logger( __FUNCTION__ );
		$csv_writer = new CsvWriter( __FUNCTION__ . '.csv' );
		$csv_writer->set_header( [ 'oid', 'post_id', 'old_url', 'new_url' ] );

		$publisher_domain       = $assoc_args['publisher-domain'];
		$slideshow_json_file    = $assoc_args['slideshow-json-file'];
		$image_json_file        = $assoc_args['image-json-file'];
		$start_from             = $assoc_args['start-from'] ?? 0;
		$end_at                 = $assoc_args['end-at'] ?? 0;
		$update_content         = $assoc_args['update-content'] ?? false;
		$gallery_mode           = $assoc_args['gallery-mode'] ?? false;
		$this->media_local_path = $assoc_args['media-local-path'] ?? '';

		$raw_slideshows               = $this->json_iterator->items( $slideshow_json_file );
		$all_migrated_slideshows_oids = array_keys( $this->load_posts() );

		$migrated_slideshows = [];

		foreach ( $raw_slideshows as $index => $slideshow ) {
			if ( $index < ( $start_from - 1 ) || ( $end_at > 0 && $index >= $end_at ) ) {
				continue;
			}
			if ( ! $update_content && in_array( $slideshow->oid, $all_migrated_slideshows_oids ) ) {
				$logger->info( sprintf( '[%d] Skipping slideshow %d because it has already been migrated', $index + 1, $slideshow->oid ) );
				continue;
			}

			$mapped_authors       = $this->map_authors( $slideshow->authors );
			$mapped_categories    = $this->map_categories( $slideshow->categories );
			$mapped_topics        = $this->map_categories( $slideshow->topics );
			$slideshow_categories = array_values( array_merge( $mapped_categories, $mapped_topics ) );

			// Check if the slideshow has non migrated authors.
			if ( count( $mapped_authors ) !== count( array_unique( $slideshow->authors ) ) ) {
				$logger->error( sprintf( 'Skipping slideshow %d because it has non migrated authors: %s', $slideshow->oid, implode( ', ', array_diff( $slideshow->authors, array_keys( $mapped_authors ) ) ) ) );
				continue;
			}

			// Check if the slideshow has non migrated categories.
			if ( count( $mapped_categories ) !== count( array_unique( $slideshow->categories ) ) ) {
				$logger->error( sprintf( 'slideshow %d has non migrated categories: %s', $slideshow->oid, implode( ', ', array_diff( $slideshow->categories, array_keys( $slideshow_categories ) ) ) ) );
			}

			// Check if the slideshow has non migrated topics.
			if ( count( $mapped_topics ) !== count( array_unique( $slideshow->topics ) ) ) {
				$logger->error( sprintf( 'slideshow %d has non migrated topics: %s', $slideshow->oid, implode( ', ', array_diff( $slideshow->topics, array_keys( $mapped_topics ) ) ) ) );
			}

			$release_date  = new \DateTime( $slideshow->releaseDate );
			$last_modified = new \DateTime( $slideshow->lastModified );

			$post_data = [
				'post_type'         => 'post',
				'post_title'        => wp_strip_all_tags( preg_replace( '/&#(?:10|13);/', '', $slideshow->title ) ),
				'post_name'         => $slideshow->basename . '-' . $slideshow->oid,
				'post_status'       => $this->map_post_status( $slideshow->status ),
				'post_date'         => $release_date->format( 'Y-m-d H:i:s' ),
				'post_date_gmt'     => $release_date->setTimezone( new \DateTimeZone( 'UTC' ) )->format( 'Y-m-d H:i:s' ),
				'post_modified'     => $last_modified->format( 'Y-m-d H:i:s' ),
				'post_modified_gmt' => $last_modified->setTimezone( new \DateTimeZone( 'UTC' ) )->format( 'Y-m-d H:i:s' ),
				'post_content'      => $slideshow->description,
				'post_category'     => $slideshow_categories,
				'comment_status'    => 'members only' === $slideshow->commentStatus ? 'open' : 'close',
			];

			$migrated_slideshow_id = Posts::create_or_get_post( $post_data, $slideshow->oid );

			if ( is_wp_error( $migrated_slideshow_id ) ) {
				$logger->error( sprintf( '[%d] Error migrating slideshow %d: %s', $index + 1, $slideshow->oid, $migrated_slideshow_id->get_error_message() ) );
				continue;
			}

			// Assign contributors.
			GuestContributorsHelper::assign_contributors_to_post( $migrated_slideshow_id, array_values( $mapped_authors ) );

			// Migrate images tray and featured image.
			$migrated_images = $this->migrate_images_tray_and_featured_image( $migrated_slideshow_id, $slideshow->imageLinks, $image_json_file, $slideshow->images ?? [], $update_content );

			// Migrate post content.
			if ( ! empty( $migrated_images ) ) {
				if ( $gallery_mode ) {
					$gallery_block = serialize_block( $this->gutenberg_block_generator->get_jetpack_slideshow( array_column( $migrated_images, 'attachment_id' ) ) );
				} else {
					$image_blocks = [];
					foreach ( $migrated_images as $image ) {
						$image_blocks[] = $this->gutenberg_block_generator->get_image( get_post( $image['attachment_id'] ) );
					}

					$gallery_block = serialize_blocks( $image_blocks );
				}

				// Migrate post content.
				$slideshow->body      = $slideshow->description;
				$migrated_description = $this->generate_post_content( $migrated_slideshow_id, $slideshow, $migrated_images, '', '', '', $slideshow_json_file, $update_content );

				$updated_content = $migrated_description . $gallery_block;

				if ( $updated_content !== $slideshow->description ) {
					// @phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
					$wpdb->update(
						$wpdb->posts,
						[ 'post_content' => $updated_content ],
						[ 'ID' => $migrated_slideshow_id ]
					);

					// If the first block is an image, hide the featured image.
					$content_blocks = parse_blocks( $updated_content );
					if ( isset( $content_blocks[0]['blockName'] ) && 'core/image' === $content_blocks[0]['blockName'] ) {
						update_post_meta( $migrated_slideshow_id, 'newspack_featured_image_position', 'hidden' );
					}
				}
			}

			// Since we regenerated the post content, we need to regenerate the post content for related posts.
			delete_post_meta( $migrated_slideshow_id, self::MIGRATED_RELATED_POSTS_META_KEY );
			delete_post_meta( $migrated_slideshow_id, self::MIGRATED_RELATED_SLIDESHOWS_META_KEY );

			// Always hide the featured image.
			update_post_meta( $migrated_slideshow_id, 'newspack_featured_image_position', 'hidden' );

			$migrated_slideshows[ $slideshow->oid ] = $migrated_slideshow_id;

			$csv_writer->put( [ $slideshow->oid, $migrated_slideshow_id, 'https://' . $publisher_domain . $slideshow->permalink, get_permalink( $migrated_slideshow_id ) ] );

			$logger->info( sprintf( '[%d] Migrated slideshow %d with ID %d', $index + 1, $slideshow->oid, $migrated_slideshow_id ) );
		}

		$csv_writer->close();
		$logger->info( sprintf( 'Check the log file for migration details: %s', __FUNCTION__ . '.log' ) );
		$logger->info( sprintf( 'Check the CSV file for migration details: %s', __FUNCTION__ . '.csv' ) );
	}

	/**
	 * Migrates Foundation related posts for both posts and slideshows received from their export.
	 * Callable for 'newspack-content-migrator foundation-migrate-related-posts' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_migrate_related_posts( array $args, array $assoc_args ): void {
		global $wpdb;

		$logger     = MultiLog::get_cli_and_file_logger( __FUNCTION__ );
		$csv_writer = new CsvWriter( __FUNCTION__ . '.csv' );
		$csv_writer->set_header( [ 'oid', 'post_id', 'old_url', 'new_url' ] );

		$publisher_domain = $assoc_args['publisher-domain'];
		$post_json_file   = $assoc_args['post-json-file'];

		$raw_posts = $this->json_iterator->items( $post_json_file );
		foreach ( $raw_posts as $post ) {
			$existing_post_id = Posts::get_post_by_unique_identifier( $post->oid );

			if ( ! $existing_post_id ) {
				$logger->error( sprintf( 'Post %d not migrated', $post->oid ) );
				continue;
			}

			$related_posts = $post->relatedStories;
			if ( empty( $related_posts ) ) {
				continue;
			}

			// Check if the post has already migrated related posts.
			if ( get_post_meta( $existing_post_id, self::MIGRATED_RELATED_POSTS_META_KEY, true ) ) {
				continue;
			}

			$mapped_related_posts = $this->map_posts( $related_posts );
			if ( count( $mapped_related_posts ) !== count( array_unique( $related_posts ) ) ) {
				$logger->error( sprintf( 'Skipping post %d because it has non migrated related posts: %s', $post->oid, implode( ', ', array_diff( $related_posts, array_keys( $mapped_related_posts ) ) ) ) );
				continue;
			}

			// Get the migrated post.
			$wp_post = get_post( $existing_post_id );
			if ( ! $wp_post ) {
				$logger->error( sprintf( 'Post %d not found', $existing_post_id ) );
				continue;
			}

			// Replace the [content-N] markers with the related posts.
			$migrated_related_posts = 0;
			$content                = preg_replace_callback(
				'/\[content-(\d+)\]/',
				function ( $matches ) use ( $post, $logger, $related_posts, $mapped_related_posts, &$migrated_related_posts ) {
					$related_story_index = (int) $matches[1] - 1; // Convert to 0-based index.
					if ( ! isset( $related_posts[ $related_story_index ] ) || ! isset( $mapped_related_posts[ $related_posts[ $related_story_index ] ] ) ) {
						$logger->warning( sprintf( 'Related story %d not found in post related stories for post %s', (int) $matches[1], $post->oid ) );
						return $matches[0];
					}

					$related_post_id = $mapped_related_posts[ $related_posts[ $related_story_index ] ];
					// Check if the marker is in the end of the post content.
					// Related posts have different styling depending if they are inline or not.
					$is_inline = ! str_ends_with( trim( wp_strip_all_tags( $post->body ) ), $matches[0] );

					++$migrated_related_posts;

					return $this->generate_related_posts_block( [ $related_post_id ], $is_inline );
				},
				$wp_post->post_content
			);

			// If we didn't migrate all the related posts, we'll add the related posts to the end of the post content.
			if ( $content === $wp_post->post_content || count( $mapped_related_posts ) !== $migrated_related_posts ) {
				// Not all the markers are present in the post content, so we'll add the related posts to the end of the post content.
				$unique_related_posts = array_values( array_unique( array_values( $mapped_related_posts ) ) );
				$content              = $content . $this->generate_related_posts_block( $unique_related_posts );
			}

			if ( $content !== $wp_post->post_content ) {
				// @phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
				$wpdb->update(
					$wpdb->posts,
					[ 'post_content' => $content ],
					[ 'ID' => $existing_post_id ]
				);

				// Mark the post as migrated related posts.
				update_post_meta( $existing_post_id, self::MIGRATED_RELATED_POSTS_META_KEY, true );

				$csv_writer->put( [ $post->oid, $existing_post_id, 'https://' . $publisher_domain . $post->permalink, get_permalink( $existing_post_id ) ] );
			}

			$logger->info( sprintf( 'Migrated related posts for post %d with ID %d', $post->oid, $existing_post_id ) );
		}

		$csv_writer->close();
		$logger->info( sprintf( 'Check the log file for migration details: %s', __FUNCTION__ . '.log' ) );
		$logger->info( sprintf( 'Check the CSV file for migration details: %s', __FUNCTION__ . '.csv' ) );
	}

	/**
	 * Migrates Foundation related slideshows received from their export.
	 * Callable for 'newspack-content-migrator foundation-migrate-related-slideshows' command.
