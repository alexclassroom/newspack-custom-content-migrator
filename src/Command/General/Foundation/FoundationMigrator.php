	/**
	 * Migrates Foundation comments received from their export.
	 * Callable for 'newspack-content-migrator foundation-migrate-comments' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_migrate_comments( array $args, array $assoc_args ): void {
		$logger     = MultiLog::get_cli_and_file_logger( __FUNCTION__ );
		$csv_writer = new CsvWriter( __FUNCTION__ . '.csv' );
		$csv_writer->set_header( [ 'oid', 'post_id', 'post_url' ] );

		$publisher_domain  = $assoc_args['publisher-domain'];
		$comment_json_file = $assoc_args['comment-json-file'];

		$raw_comments      = $this->json_iterator->items( $comment_json_file );
		$migrated_comments = $this->load_comments();

		foreach ( $raw_comments as $comment ) {
			if ( isset( $migrated_comments[ $comment->oid ] ) ) {
				continue;
			}

			if ( 'Content' !== $comment->type ) {
				$logger->error( sprintf( 'Skipping comment %s because it is not a content comment: %s', $comment->oid, $comment->type ) );
				continue;
			}

			$existing_post_id = Posts::get_post_by_unique_identifier( $comment->content );

			if ( ! $existing_post_id ) {
				$logger->error( sprintf( 'The post with oid %s not found', $comment->content ) );
				continue;
			}

			$comment_author = null;
			if ( isset( $comment->postedBy ) ) {
				$comment_author = UsersHelper::get_user_by_unique_identifier( $comment->postedBy );
			}

			$comment_date = new \DateTime( $comment->postedDate ?? $comment->lastModified ?? '' );

			$comment_data = [
				'comment_post_ID'      => $existing_post_id,
				'comment_content'      => $comment->comment,
				'comment_approved'     => 'Live' === $comment->status,
				'user_id'              => $comment_author ? $comment_author->ID : '',
				'comment_author'       => $comment_author ? $comment_author->user_nicename : $comment->name,
				'comment_author_email' => $comment_author ? $comment_author->user_email : $comment->email,
				'comment_author_url'   => $comment_author ? $comment_author->user_url : '',
				'comment_author_IP'    => $comment->ip ?? '',
				'comment_date'         => $comment_date->format( 'Y-m-d H:i:s' ),
				'comment_meta'         => [
					self::MIGRATED_COMMENT_META_KEY => $comment->oid,
				],
			];

			// Get the comment's author if is set.
			$comment_author = null;
			if ( isset( $comment->postedBy ) ) {
				$comment_author = UsersHelper::get_user_by_unique_identifier( $comment->postedBy );
			}

			if ( $comment_author ) {
				$comment_data['user_id']              = $comment_author->ID;
				$comment_data['comment_author']       = $comment_author->display_name;
				$comment_data['comment_author_email'] = $comment_author->user_email;
				$comment_data['comment_author_url']   = $comment_author->user_url;
			} else {
				$comment_data['comment_author']       = $comment->name;
				$comment_data['comment_author_email'] = $comment->email;
			}

			$comment_id = wp_insert_comment( $comment_data );

			if ( false === $comment_id ) {
				$logger->error( sprintf( 'Error migrating comment %s', $comment->oid ) );
				continue;
			}

			$csv_writer->put( [ $comment->oid, $existing_post_id, get_permalink( $existing_post_id ) ] );

			$logger->info( sprintf( 'Migrated comment %s for post %d too the commend ID: %d', $comment->oid, $existing_post_id, $comment_id ) );
		}

		$csv_writer->close();
		$logger->info( sprintf( 'Check the log file for migration details: %s', __FUNCTION__ . '.log' ) );
		$logger->info( sprintf( 'Check the CSV file for migration details: %s', __FUNCTION__ . '.csv' ) );
	}

	/**
	 * Migrates Foundation legacy redirects for both posts and slideshows received from their export.
	 * Callable for 'newspack-content-migrator foundation-migrate-legacy-redirects' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_migrate_legacy_redirects( array $args, array $assoc_args ): void {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$post_json_file   = $assoc_args['post-json-file'];
		$publisher_domain = $assoc_args['publisher-domain'];

		$raw_posts      = $this->json_iterator->items( $post_json_file );
		$migrated_posts = $this->load_posts();

		foreach ( $raw_posts as $post ) {
			if ( ! array_key_exists( $post->oid, $migrated_posts ) ) {
				$logger->error( sprintf( 'Post %s not found', $post->oid ) );
				continue;
			}

			$migrated_post_id = $migrated_posts[ $post->oid ];

			if ( isset( $post->legacyURL ) && ! empty( $post->legacyURL ) ) {
				$logger->info( sprintf( 'Migrating legacy redirect for post %s', $post->oid ) );
				$post_relative_permalink = rtrim( wp_make_link_relative( get_permalink( $migrated_post_id ) ), '/' );

				foreach ( $post->legacyURL as $legacy_url ) {
					// remove domain from the legacy URL.
					$legacy_url = rtrim( str_replace( 'https://' . $publisher_domain, '', $legacy_url ), '/' );

					if ( $post_relative_permalink !== $legacy_url ) {
						$logger->info( sprintf( 'Migrating legacy redirect for post %s (%s => %s)', $post->oid, $legacy_url, $post_relative_permalink ) );
						$this->custom_redirect_generator->add_redirect( $legacy_url, $post_relative_permalink );
					}
				}
			}
		}

		$this->custom_redirect_generator->save_redirects();
		$logger->info( sprintf( 'Saved legacy redirects. Please check the `custom-redirects.php` file.' ) );
	}

	/**
	 * Migrate Foundation user to WP user.
	 *
	 * @param object $foundation_user Foundation user.
	 * @param string $role            Role.
	 * @param object $logger          Logger.
	 *
	 * @return int|bool Migrated user ID or false if error.
	 */
	private function migrate_to_wp_user( object $foundation_user, string $role, $logger ): int|bool {
		$user_data     = [
			'role'          => $role,
			'user_login'    => $foundation_user->username,
			'user_email'    => $foundation_user->email,
			'display_name'  => $this->clean_display_name( $foundation_user->name ),
			'user_nicename' => $foundation_user->basename ?? '',
			'user_url'      => $foundation_user->website ?? '',
			'meta_input'    => [
				'description'           => $this->migrate_user_bio( $foundation_user ),
				'newspack_phone_number' => $foundation_user->phone ?? '',
				'facebook'              => $foundation_user->facebookUrl ?? '',
				'instagram'             => $foundation_user->instagramUrl ?? '',
				'linkedin'              => $foundation_user->linkedinUrl ?? '',
				'twitter'               => $foundation_user->twitterUrl ?? '',
				'youtube'               => $foundation_user->youtubeUrl ?? '',
				'bluesky'               => $foundation_user->blueskyUrl ?? '',
			],
		];
		$migrated_user = UsersHelper::create_or_get_user( $user_data, $foundation_user->oid );

		if ( is_wp_error( $migrated_user ) ) {
			$logger->error( sprintf( 'Error migrating user %s (%s): %s', $foundation_user->oid, $role, $migrated_user->get_error_message() ) );
			return false;
		}

		// Upload and set avatar if available.
		if ( isset( $foundation_user->image ) && ! empty( $foundation_user->image ) ) {
			$avatar_id = Attachments::import_external_file( $foundation_user->image );
			if ( is_wp_error( $avatar_id ) ) {
				$logger->error( sprintf( 'Error importing avatar for user %s: %s', $foundation_user->oid, $avatar_id->get_error_message() ) );
			} else {
				$this->simple_local_avatars->assign_avatar( $migrated_user->ID, $avatar_id );
			}
		}

		return $migrated_user->ID;
	}

	/**
	 * Clean display name.
	 *
	 * @param string $display_name Display name.
	 *
	 * @return string Cleaned display name.
	 */
	private function clean_display_name( string $display_name ): string {
		if ( str_starts_with( strtolower( $display_name ), 'by ' ) ) {
			return substr( $display_name, 3 );
		}

		return $display_name;
	}

	/**
	 * Format a list of items with natural language formatting (comma-separated with "and" before the last item).
	 *
	 * @param array $items Array of items to format.
	 * @return string Formatted list.
	 */
	private function format_natural_language_list( array $items ): string {
		$count = count( $items );

		if ( 0 === $count ) {
			return '';
		}

		if ( 1 === $count ) {
			return $items[0];
		}

		if ( 2 === $count ) {
			return $items[0] . ' and ' . $items[1];
		}

		// For 3 or more items: "item1, item2, and item3".
		$last_item = array_pop( $items );
		return implode( ', ', $items ) . ', and ' . $last_item;
	}

	/**
	 * Generates post content.
	 *
	 * @param int    $post_id   Post ID.
	 * @param object $post Foundation post.
	 * @param array  $migrated_images Migrated images.
	 * @param string $embed_json_file Raw embeds file.
	 * @param string $audio_json_file Raw audios file.
	 * @param string $pdf_json_file   Raw PDFs file.
	 * @param string $slideshow_json_file Raw slideshows file.
	 * @param bool   $update_content  Whether to update the content of the post.
	 *
	 * @return string Post content.
	 */
	private function generate_post_content( int $post_id, object $post, array $migrated_images, string $embed_json_file, string $audio_json_file, string $pdf_json_file, string $slideshow_json_file, bool $update_content = false ): string {
		$logger  = MultiLog::get_cli_and_file_logger( __FUNCTION__ );
		$content = $this->clean_content( $post->body );

		// Migrate info box.
		if ( ! empty( $post->infoBoxTitle ) && ! empty( $post->infoBoxText ) && ! empty( $post->infoBoxPosition ) ) {
			$content = $this->migrate_info_box( $post->oid, $content, $post->infoBoxTitle, $post->infoBoxText, $post->infoBoxPosition );
		}

		// Migrate images.
		$content = $this->migrate_images_markers( $post->oid, $content, $migrated_images, $post->imageLinks, $update_content );

		// Check if any image markers remain and try robust approach if needed.
		preg_match_all( '/\[image-(\d+)\]/', $content, $remaining_markers );
		if ( ! empty( $remaining_markers[0] ) ) {
			$logger->warning( sprintf( 'Regular image migration failed for post %s, trying robust approach. Remaining markers: %s', $post->oid, implode( ', ', $remaining_markers[0] ) ) );
			$content = $this->migrate_images_markers_robust( $post->oid, $content, $migrated_images, $post->imageLinks, $post->images ?? [], $update_content );
		}

		// Migrate pullquote.
		if ( ! empty( $post->pullquotes ) ) {
			$content = $this->migrate_pullquote_markers( $post->oid, $content, $post->pullquotes, $post->infoBoxPosition );
		}

		// Migrate embed.
		if ( ! empty( $post->embed ) ) {
			$logger->info( sprintf( 'Migrating embeds for post %s', $post->oid ) );
			$content = $this->migrate_embed_markers( $post->oid, $content, $embed_json_file, $post->embed );
		}

		// Migrate audio.
		if ( ! empty( $post->audio ) ) {
			$logger->info( sprintf( 'Migrating audio for post %s', $post->oid ) );
			$content = $this->migrate_audio_markers( $post->oid, $post_id, $content, $audio_json_file, $post->audio );
		}

		// Migrate pdf.
		if ( ! empty( $post->pdf ) ) {
			$logger->info( sprintf( 'Migrating PDFs for post %s', $post->oid ) );
			$content = $this->migrate_pdf_markers( $post->oid, $post_id, $content, $pdf_json_file, $post->pdf );
		}

		// Migrate slideshow.
		if ( ! empty( $post->slideshow ) ) {
			$content = $this->migrate_slideshow_markers( $post->oid, $content, $post->slideshow, $slideshow_json_file );
		}

		return $content;
	}

	/**
	 * Clean content.
	 *
	 * @param string $content Content.
	 *
	 * @return string Cleaned content.
	 */
	private function clean_content( string $content ): string {
		$content = $this->strip_container_div_robust( $content );
		$content = $this->strip_style_tags( $content );
		$content = $this->strip_line_breaks( $content );
		$content = $this->strip_whitespace( $content );
		$content = $this->normalize_html_list( $content );

		return $content;
	}

	/**
	 * Migrate info box.
	 *
	 * @param string $post_oid Post OID.
	 * @param string $content Post content.
	 * @param string $info_box_title Info box title.
	 * @param string $info_box_text Info box text.
	 * @param string $info_box_position Info box position.
	 *
	 * @return string Post content with info box.
	 */
	private function migrate_info_box( string $post_oid, string $content, string $info_box_title, string $info_box_text, string $info_box_position ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		if ( ! empty( $info_box_title ) && ! empty( $info_box_text ) && ! empty( $info_box_position ) ) {
			$info_box_block = serialize_block(
				$this->gutenberg_block_generator->get_group_constrained(
					[ $this->gutenberg_block_generator->get_html( $info_box_title . $info_box_text ) ],
					[ 'newspack-embed-info-box', 'alignright' ],
					[ 'align' => 'right' ]
				)
			);

			switch ( $info_box_position ) {
				case 'top':
					return $info_box_block . $content;
				case 'bottom':
					return $content . $info_box_block;
				default:
					$logger->warning( sprintf( 'Info box position %s not supported for post %s', $info_box_position, $post_oid ) );
					return $content;
			}
		}

		return $content;
	}

	/**
	 * Migrate images tray and featured image.
	 *
	 * The featured image is the image with "Teaser" placement, if not it's the one with "Magnum" placement. The "first" image is also the default Teaser if a Teaser isn't set.
	 *
	 * @param int    $post_id      Post ID.
	 * @param array  $post_image_oids  Post image OIDs.
	 * @param string $raw_images_file Raw images file.
	 * @param array  $image_urls      Image URLs to use in we don't have the raw image data.
	 *
	 * @return array Migrated images. A key-value pair of post image OID and an array with the raw image data and the attachment ID.
	 */
	private function migrate_images_tray_and_featured_image( int $post_id, array $post_image_oids, string $raw_images_file, array $image_urls, bool $update_meta = false ): array {
		global $wpdb;
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		if ( empty( $post_image_oids ) ) {
			return [];
		}

		$migrated_images           = [];
		$possible_teaser_image_ids = [];
		$possible_magnum_image_ids = [];

		foreach ( $post_image_oids as $index => $post_image_oid ) {
			$possible_raw_images = iterator_to_array( $this->json_iterator->filtered_items( $raw_images_file, 'oid', $post_image_oid ) );

			$raw_image = null;

			if ( 1 === count( $possible_raw_images ) ) {
				$raw_image = $possible_raw_images[0];
			} elseif ( isset( $image_urls[ $index ] ) ) {
				// If we can't find the image in the raw images file, we use the image URL from the images list.
				$raw_image = (object) [
					'oid' => $post_image_oid,
					'url' => $image_urls[ $index ],
				];
			}

			if ( $raw_image ) {
				$attachment_id = $this->migrate_raw_attachment( $raw_image, $post_id );

				if ( is_wp_error( $attachment_id ) ) {
					$logger->error( sprintf( 'Error migrating image %s for post %s: %s', $post_image_oid, $post_id, $attachment_id->get_error_message() ) );
					continue;
				}

				$migrated_images[ $post_image_oid ] = [
					...(array) $raw_image,
					'attachment_id' => $attachment_id,
				];

				if ( isset( $raw_image->placements ) && in_array( 'teaser', $raw_image->placements, true ) ) {
					$possible_teaser_image_ids[] = $attachment_id;
				}

				if ( isset( $raw_image->placements ) && in_array( 'magnum', $raw_image->placements, true ) ) {
					$possible_magnum_image_ids[] = $attachment_id;
				}

				if ( $update_meta ) {
					if ( isset( $raw_image->caption ) && ! empty( $raw_image->caption ) ) {
						$wpdb->update(
							$wpdb->posts,
							[ 'post_excerpt' => wp_strip_all_tags( $raw_image->caption ) ],
							[ 'ID' => $attachment_id ]
						);
					}

					if ( isset( $raw_image->credit ) && ! empty( $raw_image->credit ) ) {
						if ( str_contains( $raw_image->credit, 'href' ) ) {
							preg_match( '/href="([^"]+)"/', $raw_image->credit, $image_credit_url );
							update_post_meta( $attachment_id, '_media_credit_url', $image_credit_url[1] );
						}
						update_post_meta( $attachment_id, '_media_credit', wp_strip_all_tags( $raw_image->credit ) );
					}

					if ( isset( $raw_image->alt ) && ! empty( $raw_image->alt ) ) {
						update_post_meta( $attachment_id, '_media_alt', wp_strip_all_tags( $raw_image->alt ) );
					}
				}
			} else {
				$logger->warning( sprintf( 'Image %s not found in raw images for post %s', $post_image_oid, $post_id ) );
			}
		}

		// Warn if there are multiple teaser images.
		if ( count( $possible_teaser_image_ids ) > 1 ) {
			$logger->warning( sprintf( 'Post %s has multiple teaser images: %s', $post_id, implode( ', ', $possible_teaser_image_ids ) ) );
		}

		// Set the featured image.
		if ( ! empty( $possible_teaser_image_ids ) ) {
			set_post_thumbnail( $post_id, $possible_teaser_image_ids[0] );
		} elseif ( ! empty( $possible_magnum_image_ids ) ) {
			set_post_thumbnail( $post_id, $possible_magnum_image_ids[0] );
		} elseif ( ! empty( $migrated_images ) ) {
			$first_image = current( $migrated_images );
			set_post_thumbnail( $post_id, $first_image['attachment_id'] );
		}

		return $migrated_images;
	}

	/**
	 * Migrate images markers.
	 *
	 * Image markers in the content are in the format: [image-N] where N is a 1-based index.
	 * For example: [image-1] refers to the first image, [image-2] to the second, etc.
	 * This method converts these 1-based indices to 0-based indices for array access.
	 *
	 * @param string $post_oid     Post OID.
	 * @param string $content      Post content.
	 * @param array  $migrated_images   Migrated images. A key-value pair of post image OID and an array with the raw image data and the attachment ID.
	 * @param array  $post_image_oids  Post image OIDs. A 0-based indexed array.
	 *
	 * @return string Post content with image markers replaced by Gutenberg blocks.
	 */
	private function migrate_images_markers( string $post_oid, string $content, array $migrated_images, array $post_image_oids ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		// Debug: Log initial state.
		$logger->info( sprintf( 'Starting image marker migration for post %s', $post_oid ) );
		$logger->info( sprintf( 'Content length: %d', strlen( $content ) ) );
		$logger->info( sprintf( 'Number of migrated images: %d', count( $migrated_images ) ) );
		$logger->info( sprintf( 'Number of post image OIDs: %d', count( $post_image_oids ) ) );

		// Count image markers in content before replacement.
		preg_match_all( '/\[image-(\d+)\]/', $content, $marker_matches );
		$marker_count = count( $marker_matches[0] );
		$logger->info( sprintf( 'Found %d image markers in content', $marker_count ) );

		if ( $marker_count > 0 ) {
			$logger->info( sprintf( 'Image markers found: %s', implode( ', ', $marker_matches[0] ) ) );
		}

		$content = preg_replace_callback(
			'/\[image-(\d+)\]/',
			function ( $matches ) use ( $post_oid, $migrated_images, $logger, $post_image_oids ) {
				$image_index = (int) $matches[1] - 1; // Convert to 0-based index.
				$logger->info( sprintf( 'Processing image marker [image-%d] (index %d)', (int) $matches[1], $image_index ) );

				if ( ! isset( $post_image_oids[ $image_index ] ) ) {
					$logger->warning( sprintf( 'Image index %d not found in post_image_oids array for post %s', $image_index, $post_oid ) );
					$logger->warning( sprintf( 'Available indices: %s', implode( ', ', array_keys( $post_image_oids ) ) ) );
					return $matches[0];
				}

				$image_oid = $post_image_oids[ $image_index ];
				$logger->info( sprintf( 'Image OID: %s', $image_oid ) );

				if ( ! isset( $migrated_images[ $image_oid ] ) ) {
					$logger->warning( sprintf( 'Image OID %s not found in migrated_images for post %s', $image_oid, $post_oid ) );
					$logger->warning( sprintf( 'Available migrated image OIDs: %s', implode( ', ', array_keys( $migrated_images ) ) ) );
					return $matches[0];
				}

				$raw_image = $migrated_images[ $image_oid ];
				$logger->info( sprintf( 'Found raw image data for OID %s', $image_oid ) );

				$attachment_post = get_post( $raw_image['attachment_id'] );

				if ( ! $attachment_post ) {
					$logger->warning( sprintf( 'Attachment post %d not found for image %d in post %s', $raw_image['attachment_id'], (int) $matches[1], $post_oid ) );
					return $matches[0];
				}

				$logger->info( sprintf( 'Found attachment post %d for image %d', $raw_image['attachment_id'], (int) $matches[1] ) );

				$classes = '';
				if ( ! empty( $raw_image['alignment'] ) ) {
					$classes = 'align' . strtolower( $raw_image['alignment'] );
				}

				$destination_url = $raw_image['destinationURL'] ?? null;
				$alignment       = isset( $raw_image['alignment'] ) ? strtolower( $raw_image['alignment'] ) : null;

				$replacement = serialize_block( $this->gutenberg_block_generator->get_image( $attachment_post, 'full', true, $classes, $alignment, $destination_url ) );
				$logger->info( sprintf( 'Successfully generated replacement for image %d', (int) $matches[1] ) );

				return $replacement;
			},
			$content
		);

		// Debug: Check if any markers remain after replacement.
		preg_match_all( '/\[image-(\d+)\]/', $content, $remaining_matches );
		$remaining_count = count( $remaining_matches[0] );

		if ( $remaining_count > 0 ) {
			$logger->warning( sprintf( 'After replacement, %d image markers remain: %s', $remaining_count, implode( ', ', $remaining_matches[0] ) ) );
		} else {
			$logger->info( sprintf( 'All image markers successfully replaced for post %s', $post_oid ) );
		}

		return $content;
	}

	/**
	 * Migrate pullquote markers.
	 *
	 * Pullquote markers in the content are in the format: [pullquote-N] where N is a 1-based index.
	 * For example: [pullquote-1-center] refers to the first pullquote, [pullquote-2] to the second, etc.
	 * This method converts these 1-based indices to 0-based indices for array access.
	 *
	 * @param string $post_oid        Post OID.
	 * @param string $content         Post content.
	 * @param array  $post_pullquotes Post pullquotes array (0-based indexed).
	 * @param string $info_box_position Info box position.
	 *
	 * @return string Post content with pullquote markers replaced by their content.
	 */
	private function migrate_pullquote_markers( string $post_oid, string $content, array $post_pullquotes, string $info_box_position ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$content = preg_replace_callback(
			'/\[pullquote-(\d+)(?:-(\w+))?\]/',
			function ( $matches ) use ( $post_oid, $logger, $post_pullquotes ) {
				$pullquote_index = (int) $matches[1] - 1; // Convert to 0-based index.
				if ( ! isset( $post_pullquotes[ $pullquote_index ] ) ) {
					$logger->warning( sprintf( 'Pullquote %d not found in post pullquotes for post %s', (int) $matches[1], $post_oid ) );
					return $matches[0];
				}
				return serialize_block( $this->gutenberg_block_generator->get_quote( $post_pullquotes[ $pullquote_index ] ) );
			},
			$content
		);

		return $content;
	}

	/**
	 * Migrate embed markers.
	 *
	 * Embed markers in the content are in the format: [embed-N] where N is a 1-based index.
	 * For example: [embed-1] refers to the first embed, [embed-2] to the second, etc.
	 * This method converts these 1-based indices to 0-based indices for array access.
	 *
	 * @param string $post_oid    Post OID.
	 * @param string $content     Post content.
	 * @param string $embed_json_file Raw embeds file.
	 * @param array  $post_embeds Post embeds array (0-based indexed).
	 *
	 * @return string Post content with embed markers replaced by Gutenberg blocks.
	 */
	private function migrate_embed_markers( string $post_oid, string $content, string $embed_json_file, array $post_embeds ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		if ( empty( $post_embeds ) ) {
			return $content;
		}

		// If the content contains [embed-N] markers, we need to migrate the embeds in their place.
		// If not, we need to add a embed block to the end of the content.
		if ( ! preg_match( '/\[embed-(\d+)\]/', $content ) ) {
			$embed_id            = current( $post_embeds );
			$possible_raw_embeds = iterator_to_array( $this->json_iterator->filtered_items( $embed_json_file, 'oid', $embed_id ) );

			if ( 1 === count( $possible_raw_embeds ) ) {
				$raw_embed      = $possible_raw_embeds[0];
				$migrated_embed = $this->migrate_raw_embed( $raw_embed );

				if ( is_wp_error( $migrated_embed ) ) {
					$logger->error( sprintf( 'Error migrating embed %s for post %s: %s', $embed_id, $post_oid, $migrated_embed->get_error_message() ) );
					return $content;
				}

				return $content . $migrated_embed;
			}

			$logger->warning( sprintf( 'Embed %d not found in raw embeds for post %s', $embed_id, $post_oid ) );
			return $content;
		}

		$content = preg_replace_callback(
			'/\[embed-(\d+)\]/',
			function ( $matches ) use ( $post_oid, $embed_json_file, $logger, $post_embeds ) {
				$embed_index = (int) $matches[1] - 1; // Convert to 0-based index.
				if ( ! isset( $post_embeds[ $embed_index ] ) ) {
					$logger->warning( sprintf( 'Embed %d not found in post embeds for post %s', (int) $matches[1], $post_oid ) );
					return $matches[0];
				}
				$embed_id            = $post_embeds[ $embed_index ];
				$possible_raw_embeds = iterator_to_array( $this->json_iterator->filtered_items( $embed_json_file, 'oid', $embed_id ) );

				if ( 1 === count( $possible_raw_embeds ) ) {
					$raw_embed      = $possible_raw_embeds[0];
					$migrated_embed = $this->migrate_raw_embed( $raw_embed );

					if ( is_wp_error( $migrated_embed ) ) {
						$logger->error( sprintf( 'Error migrating embed %s for post %s: %s', $matches[1], $post_oid, $migrated_embed->get_error_message() ) );
						return $matches[0];
					}

					return $migrated_embed;
				}

				$logger->warning( sprintf( 'Embed %d not found in raw embeds for post %s', $matches[1], $post_oid ) );
				return $matches[0];
			},
			$content
		);

		return $content;
	}

	/**
	 * Migrate audio markers.
	 *
	 * Audio markers in the content are in the format: [audio-N] where N is a 1-based index.
	 * For example: [audio-1] refers to the first audio, [audio-2] to the second, etc.
	 * This method converts these 1-based indices to 0-based indices for array access.
	 *
	 * @param string $post_oid   Post OID.
	 * @param int    $post_id    Post ID.
	 * @param string $content    Post content.
	 * @param string $audio_json_file Raw audios file.
	 * @param array  $post_audio Post audio array (0-based indexed).
	 *
	 * @return string Post content with audio markers replaced by Gutenberg blocks.
	 */
	private function migrate_audio_markers( string $post_oid, int $post_id, string $content, string $audio_json_file, array $post_audio ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$content = preg_replace_callback(
			'/\[audio-(\d+)\]/',
			function ( $matches ) use ( $post_oid, $audio_json_file, $post_id, $logger, $post_audio ) {
				$audio_index = (int) $matches[1] - 1; // Convert to 0-based index.
				if ( ! isset( $post_audio[ $audio_index ] ) ) {
					$logger->warning( sprintf( 'Audio %d not found in post audio for post %s', (int) $matches[1], $post_oid ) );
					return $matches[0];
				}
				$audio_id            = $post_audio[ $audio_index ];
				$possible_raw_audios = iterator_to_array( $this->json_iterator->filtered_items( $audio_json_file, 'oid', $audio_id ) );

				if ( 1 === count( $possible_raw_audios ) ) {
					$raw_audio     = $possible_raw_audios[0];
					$attachment_id = $this->migrate_raw_attachment( $raw_audio, $post_id );

					if ( is_wp_error( $attachment_id ) ) {
						$logger->error( sprintf( 'Error migrating audio %s for post %s: %s', $matches[1], $post_oid, $attachment_id->get_error_message() ) );
						return $matches[0];
					}

					return serialize_block( $this->gutenberg_block_generator->get_audio( get_post( $attachment_id ), $raw_audio->caption ) );
				}

				$logger->warning( sprintf( 'Audio %d not found in raw audios for post %s', $matches[1], $post_oid ) );
				return $matches[0];
			},
			$content
		);

		return $content;
	}

	/**
	 * Migrate PDF markers.
	 *
	 * PDF markers in the content are in the format: [pdf-N] where N is a 1-based index.
	 * For example: [pdf-1] refers to the first PDF, [pdf-2] to the second, etc.
	 * This method converts these 1-based indices to 0-based indices for array access.
	 *
	 * @param string $post_oid  Post OID.
	 * @param int    $post_id   Post ID.
	 * @param string $content   Post content.
	 * @param string $pdf_json_file Raw PDFs file.
	 * @param array  $post_pdfs Post PDFs array (0-based indexed).
	 *
	 * @return string Post content with PDF markers replaced by Gutenberg blocks.
	 */
	private function migrate_pdf_markers( string $post_oid, int $post_id, string $content, string $pdf_json_file, array $post_pdfs ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$content = preg_replace_callback(
			'/\[pdf-(\d+)\]/',
			function ( $matches ) use ( $post_oid, $pdf_json_file, $post_id, $logger, $post_pdfs ) {
				$pdf_index = (int) $matches[1] - 1; // Convert to 0-based index.
				if ( ! isset( $post_pdfs[ $pdf_index ] ) ) {
					$logger->warning( sprintf( 'PDF %d not found in post pdfs for post %s', (int) $matches[1], $post_oid ) );
					return $matches[0];
				}
				$pdf_id            = $post_pdfs[ $pdf_index ];
				$possible_raw_pdfs = iterator_to_array( $this->json_iterator->filtered_items( $pdf_json_file, 'oid', $pdf_id ) );

				if ( 1 === count( $possible_raw_pdfs ) ) {
					$raw_pdf       = $possible_raw_pdfs[0];
					$attachment_id = $this->migrate_raw_attachment( $raw_pdf, $post_id );

					if ( is_wp_error( $attachment_id ) ) {
						$logger->error( sprintf( 'Error migrating pdf %s for post %s: %s', $matches[1], $post_oid, $attachment_id->get_error_message() ) );
						return $matches[0];
					}

					// TODO: Check the specialHandling field.
					return serialize_block( $this->gutenberg_block_generator->get_pdf( $attachment_id, $raw_pdf->caption ) );
				}

				$logger->warning( sprintf( 'PDF %d not found in raw pdfs for post %s', $matches[1], $post_oid ) );
				return $matches[0];
			},
			$content
		);

		return $content;
	}

	/**
	 * Migrate slideshow markers.
	 *
	 * @param string $post_oid        Post OID.
	 * @param string $content         Post content.
	 * @param array  $post_slideshow Post slideshow array (0-based indexed).
	 * @param string $slideshow_json_file Raw slideshows file.
	 *
	 * @return string Post content with slideshow markers replaced by Gutenberg blocks.
	 */
	private function migrate_slideshow_markers( string $post_oid, string $content, array $post_slideshow, string $slideshow_json_file ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		if ( empty( $post_slideshow ) ) {
			return $content;
		}

		// If the content contains [slideshow-N] markers, we need to migrate the slideshows in their place.
		// If not, we need to add a slideshow block to the end of the content.

		// Check if the marker is in the content.
		if ( ! preg_match( '/\[slideshow-(\d+)\]/', $content ) ) {
			$slideshow_wp_post_id = Posts::get_post_by_unique_identifier( $post_slideshow[0] );

			if ( ! $slideshow_wp_post_id ) {
				$logger->warning( sprintf( 'Slideshow post %d not found for post %s', $post_slideshow[0], $post_oid ) );
				return $content;
			}

			$related_slideshows_block = $this->generate_content_slideshows_block( $slideshow_wp_post_id );
			return $content . $related_slideshows_block;
		}

		$content = preg_replace_callback(
			'/\[slideshow-(\d+)\]/',
			function ( $matches ) use ( $post_oid, $slideshow_json_file, $logger, $post_slideshow ) {
				$slideshow_index = (int) $matches[1] - 1; // Convert to 0-based index.
				if ( ! isset( $post_slideshow[ $slideshow_index ] ) ) {
					$logger->warning( sprintf( 'Slideshow %d not found in post slideshows for post %s', (int) $matches[1], $post_oid ) );
					return $matches[0];
				}
				$slideshow_wp_post_id = Posts::get_post_by_unique_identifier( $post_slideshow[ $slideshow_index ] );

				if ( ! $slideshow_wp_post_id ) {
					$logger->warning( sprintf( 'Slideshow post %d not found for post %s', $post_slideshow[ $slideshow_index ], $post_oid ) );
					return $matches[0];
				}

				$related_slideshows_block = $this->generate_content_slideshows_block( $slideshow_wp_post_id );
				return $related_slideshows_block;
			},
			$content
		);

		return $content;
	}

	/**
	 * Migrate raw attachment.
	 *
	 * @param object $raw_attachment Raw attachment.
	 * @param int    $post_id   Post ID.
	 *
	 * @return int|WP_Error Attachment ID or WP_Error.
	 */
	private function migrate_raw_attachment( object $raw_attachment, int $post_id ) {
		$caption = isset( $raw_attachment->caption ) ? wp_strip_all_tags( $raw_attachment->caption ) : '';
		$alt     = isset( $raw_attachment->alt ) ? wp_strip_all_tags( $raw_attachment->alt ) : '';

		$credit_url = '';
		$credit     = '';
		if ( isset( $raw_attachment->credit ) && ! empty( $raw_attachment->credit ) ) {
			if ( str_contains( $raw_attachment->credit, 'href' ) ) {
				preg_match( '/href="([^"]+)"/', $raw_attachment->credit, $image_credit_url );
				$credit_url = $image_credit_url[1];
			}

			$credit = wp_strip_all_tags( $raw_attachment->credit );
		}

		$meta_input = [
			'meta_input' => [
				'_media_credit'     => $credit,
				'_media_credit_url' => $credit_url,
			],
		];

		$local_media_path = isset( $raw_attachment->path ) ? rtrim( $this->media_local_path, '/' ) . '/' . ltrim( $raw_attachment->path, '/' ) : '';
		$media_path       = is_file( $local_media_path ) ? $local_media_path : $raw_attachment->url;

		return Attachments::import_external_file( $media_path, null, $caption, null, $alt, $post_id, $meta_input, '', true, $raw_attachment->oid );
	}

