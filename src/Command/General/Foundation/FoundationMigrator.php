	/**
	 * Strips container divs robustly.
	 *
	 * @param string $html The HTML content to process.
	 * @return string The processed HTML content.
	 */
	private function strip_container_div_robust( string $html ): string {
		// Trim whitespace.
		$html = trim( $html );

		// Keep processing until no more attribute-less divs are found.
		$previous_length = 0;
		$current_length  = strlen( $html );
		while ( $current_length !== $previous_length ) {
			$previous_length = $current_length;
			$html            = $this->strip_attribute_less_divs( $html );
			$current_length  = strlen( $html );
		}

		return $html;
	}

	/**
	 * Strips style attributes from all tags and preserves HTML comments.
	 *
	 * @param string $html The HTML content to process.
	 * @return string The processed HTML content.
	 */
	private function strip_style_tags( string $html ): string {
		// Temporarily replace HTML comments to preserve them during processing.
		$comment_placeholders = [];
		$html                 = preg_replace_callback(
			'/<!--.*?-->/s',
			function ( $matches ) use ( &$comment_placeholders ) {
				$placeholder                          = '<!--COMMENT_PLACEHOLDER_' . count( $comment_placeholders ) . '-->';
				$comment_placeholders[ $placeholder ] = $matches[0];
				return $placeholder;
			},
			$html
		);

		// Temporarily replace script tags to preserve them during wp_kses processing.
		$script_placeholders = [];
		$html                = preg_replace_callback(
			'/<script[^>]*>.*?<\/script>/is',
			function ( $matches ) use ( &$script_placeholders ) {
				$placeholder                         = '<!--SCRIPT_PLACEHOLDER_' . count( $script_placeholders ) . '-->';
				$script_placeholders[ $placeholder ] = $matches[0];
				return $placeholder;
			},
			$html
		);

		// Temporarily replace style tags to preserve them during wp_kses processing.
		$style_placeholders = [];
		$html               = preg_replace_callback(
			'/<style[^>]*>.*?<\/style>/is',
			function ( $matches ) use ( &$style_placeholders ) {
				$placeholder                        = '<!--STYLE_PLACEHOLDER_' . count( $style_placeholders ) . '-->';
				$style_placeholders[ $placeholder ] = $matches[0];
				return $placeholder;
			},
			$html
		);

		$allowed_tags = wp_kses_allowed_html( 'post' );

		// Remove style attribute from all tags.
		foreach ( $allowed_tags as $tag => $attributes ) {
			unset( $allowed_tags[ $tag ]['style'] );
		}

		// Process with wp_kses.
		$html = wp_kses( $html, $allowed_tags, wp_allowed_protocols() );

		// Restore script tags.
		foreach ( $script_placeholders as $placeholder => $script_tag ) {
			$html = str_replace( $placeholder, $script_tag, $html );
		}

		// Restore style tags.
		foreach ( $style_placeholders as $placeholder => $style_tag ) {
			$html = str_replace( $placeholder, $style_tag, $html );
		}

		// Restore HTML comments.
		foreach ( $comment_placeholders as $placeholder => $comment ) {
			$html = str_replace( $placeholder, $comment, $html );
		}

		return $html;
	}



	/**
	 * Strips unnecessary line break lines.
	 *
	 * @param string $html The HTML content to process.
	 * @return string The processed HTML content.
	 */
	private function strip_line_breaks( string $html ): string {
		// Remove <br> and newlines inside the dropcap span.
		$html = preg_replace_callback(
			'/<span class="fdnDropCap">.*?<\/span>/is',
			function ( $matches ) {
				return preg_replace( '/<br\s*\/?>|\R/i', '', $matches[0] );
			},
			$html
		);

		// Remove any <br> tags (with or without \n) immediately after </span>.
		$html = preg_replace( '/(<\/span>)(\s*<br\s*\/?>\s*|\s*\n\s*)+/i', '$1 ', $html );

		// Match one or more <br> tags in a row (with optional whitespace/newlines).
		$normalized = preg_replace( '/(<br\s*\/?>\s*){2,}/i', '###PARA_BREAK###', $html );

		// Split on our placeholder.
		$paragraphs = explode( '###PARA_BREAK###', $normalized );

		// Wrap each paragraph.
		$output = '';
		foreach ( $paragraphs as $p ) {
			$trimmed = trim( $p );
			if ( ! empty( $trimmed ) && ! str_starts_with( $trimmed, '<p>' ) && ! str_starts_with( $trimmed, '[' ) ) {
				$output .= '<p>' . $trimmed . '</p>' . "\n";
			} else {
				$output .= $trimmed . "\n";
			}
		}

		return $output;
	}

	/**
	 * Strips unnecessary whitespace.
	 *
	 * @param string $html The HTML content to process.
	 * @return string The processed HTML content.
	 */
	private function strip_whitespace( string $html ): string {
		// Remove excessive whitespace between closing tag and the first character of its content.
		$html = preg_replace( '/>\s+(\S)/', '> $1', $html );
		// Remove excessive whitespace between tags.
		$html = preg_replace( '/>\s+</', '> <', $html );
		$html = preg_replace( '/\]\s+</', '] <', $html );
		$html = preg_replace( '/>\s+\[/', '> [', $html );

		return trim( $html );
	}

	/**
	 * Normalizes HTML lists to a standard format by cleaning up whitespace and formatting.
	 * Groups multiple single-item ul tags into one consolidated ul tag.
	 *
	 * @param string $html The HTML content to process.
	 * @return string The processed HTML content with normalized lists.
	 */
	private function normalize_html_list( string $html ): string {
		// Group consecutive single-item ul tags into one ul tag.
		$html = preg_replace_callback(
			'/(<ul[^>]*>\s*<li[^>]*>.*?<\/li>\s*<\/ul>\s*(?:<br[^>]*>\s*)*)+/is',
			function ( $matches ) {
				$all_ul_content = $matches[0];

				// Extract all li tags from the matched ul tags.
				preg_match_all( '/<li[^>]*>(.*?)<\/li>/is', $all_ul_content, $li_matches );

				if ( empty( $li_matches[0] ) ) {
					return $matches[0]; // Return unchanged if no li tags found.
				}

				$cleaned_li_tags = [];
				foreach ( $li_matches[1] as $index => $li_content ) {
					// Clean up the content of each li tag.
					$cleaned_content = preg_replace( '/\s+/', ' ', $li_content );
					$cleaned_content = trim( $cleaned_content );

					$cleaned_li_tags[] = '<li>' . $cleaned_content . '</li>';
				}

				// Return a single ul tag containing all the cleaned li tags.
				return '<ul>' . implode( '', $cleaned_li_tags ) . '</ul>';
			},
			$html
		);

		// Group consecutive single-item ol tags into one ol tag.
		$html = preg_replace_callback(
			'/(<ol[^>]*>\s*<li[^>]*>.*?<\/li>\s*<\/ol>\s*(?:<br[^>]*>\s*)*)+/is',
			function ( $matches ) {
				$all_ol_content = $matches[0];

				// Extract all li tags from the matched ol tags.
				preg_match_all( '/<li[^>]*>(.*?)<\/li>/is', $all_ol_content, $li_matches );

				if ( empty( $li_matches[0] ) ) {
					return $matches[0]; // Return unchanged if no li tags found.
				}

				$cleaned_li_tags = [];
				foreach ( $li_matches[1] as $index => $li_content ) {
					// Clean up the content of each li tag.
					$cleaned_content = preg_replace( '/\s+/', ' ', $li_content );
					$cleaned_content = trim( $cleaned_content );

					$cleaned_li_tags[] = '<li>' . $cleaned_content . '</li>';
				}

				// Return a single ol tag containing all the cleaned li tags.
				return '<ol>' . implode( '', $cleaned_li_tags ) . '</ol>';
			},
			$html
		);

		return $html;
	}

	/**
	 * Helper function to strip one level of attribute-less divs.
	 *
	 * @param string $html The HTML content to process.
	 * @return string The processed HTML content.
	 */
	private function strip_attribute_less_divs( string $html ): string {
		// Use regex to find and replace attribute-less divs.
		// This pattern matches <div>content</div> where div has no attributes.
		$pattern = '/<div(?:\s+[^>]*)?>(.*?)<\/div>/s';

		// Keep replacing until no more matches.
		$previous_html = '';
		while ( $html !== $previous_html ) {
			$previous_html = $html;
			$html          = preg_replace_callback(
				$pattern,
				function ( $matches ) {
					// Check if the div tag has attributes.
					$div_tag         = $matches[0];
					$div_start       = strpos( $div_tag, '<div' );
					$div_end         = strpos( $div_tag, '>', $div_start );
					$div_tag_content = substr( $div_tag, $div_start, $div_end - $div_start + 1 );

					// If div has attributes (like class, id, style, etc.), keep it.
					if ( preg_match( '/<div\s+[^>]*>/', $div_tag_content ) ) {
						return $matches[0]; // Return unchanged.
					}

					// If div has no attributes, return just the content.
					return $matches[1];
				},
				$html
			);
		}

		return $html;
	}

	/**
	 * Migrate images markers with robust replacement.
	 * This method ensures all image markers are replaced by iterating until no more replacements can be made.
	 *
	 * @param string $post_oid     Post OID.
	 * @param string $content      Post content.
	 * @param array  $migrated_images   Migrated images. A key-value pair of post image OID and an array with the raw image data and the attachment ID.
	 * @param array  $post_image_oids Post image OIDs. A 0-based indexed array.
	 * @param array  $image_urls   Image URLs from the images field. A 0-based indexed array.
	 * @param bool   $update_meta  Whether to update the meta data of the image.
	 *
	 * @return string Post content with image markers replaced by Gutenberg blocks.
	 */
	private function migrate_images_markers_robust( string $post_oid, string $content, array $migrated_images, array $post_image_oids, array $image_urls, bool $update_meta = false ): string {
		global $wpdb;
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$logger->info( sprintf( 'Starting robust image marker migration for post %s', $post_oid ) );

		$max_iterations   = 10; // Prevent infinite loops.
		$iteration        = 0;
		$previous_content = '';
		$content_updated  = $content;

		while ( $iteration < $max_iterations && $content_updated !== $previous_content ) {
			$previous_content = $content_updated;
			++$iteration;

			$logger->info( sprintf( 'Iteration %d for post %s', $iteration, $post_oid ) );

			// Count remaining markers.
			preg_match_all( '/\[image-(\d+)\]/', $content_updated, $marker_matches );
			$marker_count = count( $marker_matches[0] );

			if ( 0 === $marker_count ) {
				$logger->info( sprintf( 'No more image markers found after iteration %d', $iteration ) );
				break;
			}

			$logger->info( sprintf( 'Found %d image markers in iteration %d: %s', $marker_count, $iteration, implode( ', ', $marker_matches[0] ) ) );

			$content_updated = preg_replace_callback(
				'/\[image-(\d+)\]/',
				function ( $matches ) use ( $post_oid, $migrated_images, $logger, $post_image_oids, $image_urls, $iteration, $wpdb, $update_meta ) {
					$image_index = (int) $matches[1] - 1; // Convert to 0-based index.
					$logger->info( sprintf( 'Iteration %d: Processing image marker [image-%d] (index %d)', $iteration, (int) $matches[1], $image_index ) );

					// Try to find the image in migrated_images first.
					$attachment_id = null;
					$raw_image     = null;

					// Look for the image in migrated_images by index.
					$image_oid = $post_image_oids[ $image_index ];
					if ( array_key_exists( $image_oid, $migrated_images ) ) {
						$raw_image     = $migrated_images[ $image_oid ];
						$attachment_id = $raw_image['attachment_id'];
						$logger->info( sprintf( 'Iteration %d: Found image in migrated_images with OID %s', $iteration, $image_oid ) );
					}

					// If not found in migrated_images, try to download from URL.
					if ( ! $attachment_id && isset( $image_urls[ $image_index ] ) ) {
						$image_url = $image_urls[ $image_index ];
						$logger->info( sprintf( 'Iteration %d: Attempting to download image from URL: %s', $iteration, $image_url ) );

						// Create a temporary raw image object for download.
						$temp_raw_image = (object) [
							'oid' => $image_oid,
							'url' => $image_url,
						];

						$attachment_id = $this->migrate_raw_attachment( $temp_raw_image, 0 ); // Use 0 as post_id for now.

						if ( is_wp_error( $attachment_id ) ) {
							$logger->warning( sprintf( 'Iteration %d: Failed to download image from URL: %s', $iteration, $image_url ) );
							return $matches[0];
						}

						$logger->info( sprintf( 'Iteration %d: Successfully downloaded image with attachment ID %d', $iteration, $attachment_id ) );
					}

					if ( ! $attachment_id ) {
						$logger->warning( sprintf( 'Iteration %d: No image found for index %d in post %s', $iteration, $image_index, $post_oid ) );
						return $matches[0];
					}

					$attachment_post = get_post( $attachment_id );

					if ( ! $attachment_post ) {
						$logger->warning( sprintf( 'Iteration %d: Attachment post %d not found for image %d in post %s', $iteration, $attachment_id, (int) $matches[1], $post_oid ) );
						return $matches[0];
					}

					$logger->info( sprintf( 'Iteration %d: Found attachment post %d for image %d', $iteration, $attachment_id, (int) $matches[1] ) );

					$classes         = '';
					$alignment       = null;
					$destination_url = null;

					// Use raw_image data if available.
					if ( $raw_image ) {
						if ( ! empty( $raw_image['alignment'] ) ) {
							$classes = 'align' . strtolower( $raw_image['alignment'] );
						}
						$destination_url = $raw_image['destinationURL'] ?? null;
						$alignment       = isset( $raw_image['alignment'] ) ? strtolower( $raw_image['alignment'] ) : null;

						if ( $update_meta ) {
							if ( isset( $raw_image->caption ) && ! empty( $raw_image->caption ) ) {
								$wpdb->update(
									$wpdb->posts,
									[ 'post_excerpt' => wp_strip_all_tags( $raw_image->caption ) ],
									[ 'ID' => $attachment_id ]
								);
							}

							if ( isset( $raw_image->credit ) && ! empty( $raw_image->credit ) ) {
								if ( str_contains( $raw_image->credit, 'href' ) ) {
									preg_match( '/href="([^"]+)"/', $raw_image->credit, $image_credit_url );
									update_post_meta( $attachment_id, '_media_credit_url', $image_credit_url[1] );
								}
								update_post_meta( $attachment_id, '_media_credit', wp_strip_all_tags( $raw_image->credit ) );
							}

							if ( isset( $raw_image->alt ) && ! empty( $raw_image->alt ) ) {
								update_post_meta( $attachment_id, '_media_alt', wp_strip_all_tags( $raw_image->alt ) );
							}
						}
					}

					$replacement = serialize_block( $this->gutenberg_block_generator->get_image( $attachment_post, 'full', true, $classes, $alignment, $destination_url ) );
					$logger->info( sprintf( 'Iteration %d: Successfully generated replacement for image %d', $iteration, (int) $matches[1] ) );

					return $replacement;
				},
				$content_updated
			);
		}

		// Final check for remaining markers.
		preg_match_all( '/\[image-(\d+)\]/', $content_updated, $remaining_matches );
		$remaining_count = count( $remaining_matches[0] );

		if ( $remaining_count > 0 ) {
			$logger->warning( sprintf( 'After %d iterations, %d image markers remain for post %s: %s', $iteration, $remaining_count, $post_oid, implode( ', ', $remaining_matches[0] ) ) );
		} else {
			$logger->info( sprintf( 'All image markers successfully replaced for post %s after %d iterations', $post_oid, $iteration ) );
		}

		if ( $iteration >= $max_iterations ) {
			$logger->warning( sprintf( 'Reached maximum iterations (%d) for post %s', $max_iterations, $post_oid ) );
		}

		return $content_updated;
	}
}
