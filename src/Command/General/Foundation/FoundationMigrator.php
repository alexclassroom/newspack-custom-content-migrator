	/**
	 * Migrate raw attachment.
	 *
	 * @param object $raw_attachment Raw attachment.
	 * @param int    $post_id   Post ID.
	 *
	 * @return int|WP_Error Attachment ID or WP_Error.
	 */
	private function migrate_raw_attachment( object $raw_attachment, int $post_id ) {
		$meta_input = [
			'meta_input' => [
				'foundation_oid' => $raw_attachment->oid,
			],
		];

		return Attachments::import_external_file( $raw_attachment->url, null, $raw_attachment->caption, null, $raw_attachment->alt ?? null, $post_id, $meta_input );
	}

	/**
	 * Migrate raw embed.
	 *
	 * @param object $raw_embed Raw embed.
	 *
	 * @return string|WP_Error Embed HTML or WP_Error.
	 */
	private function migrate_raw_embed( object $raw_embed ) {
		$classes = [ 'newspack-embed-container' ];
		$attrs   = [];

		// YouTube embed.
		if ( isset( $raw_embed->hostingProvider ) && 'youtube' === $raw_embed->hostingProvider ) {
			if ( ! isset( $raw_embed->embedURL ) ) {
				return new \WP_Error( 'missing_embed_url', 'Embed URL is missing' );
			}

			return serialize_block( $this->gutenberg_block_generator->get_youtube( $raw_embed->embedURL ) );
		}

		if ( isset( $raw_embed->specialPlacement ) && in_array( 'Info Box', $raw_embed->specialPlacement, true ) ) {
			$classes[] = 'newspack-embed-info-box';
		}

		if ( isset( $raw_embed->alignment ) ) {
			$attrs['align'] = strtolower( $raw_embed->alignment );
			$classes[]      = 'align' . strtolower( $raw_embed->alignment );
		}

		return serialize_block(
			$this->gutenberg_block_generator->get_group_constrained(
				[
					$this->gutenberg_block_generator->get_html( $raw_embed->body ),
				],
				$classes,
				$attrs
			)
		);
	}

	/**
	 * Migrate user bio.
	 *
	 * @param object $user User.
	 * @return string User bio.
	 */
	private function migrate_user_bio( object $user ): string {
		$bio_parts = [];

		if ( ! empty( $user->statusTagline ) ) {
			$bio_parts[] = $user->statusTagline;
		}

		if ( ! empty( $user->bio ) ) {
			$bio_parts[] = $user->bio;
		}

		return implode( "\n\n", $bio_parts );
	}

	/**
	 * Maps Foundation post status to WordPress post status.
	 *
	 * @param string $status Foundation post status.
	 * @return string WordPress post status.
	 */
	private function map_post_status( string $status ): string {
		switch ( $status ) {
			case 'Live':
				return 'publish';
			case 'Draft':
				return 'draft';
			case 'Pending Review':
				return 'pending';
			case 'Offline':
				return 'trash';
			case 'Scheduled':
				return 'future';
			default:
				return 'publish';
		}
	}

	/**
	 * Maps Foundation author to WordPress author.
	 *
	 * @param array $authors Foundation authors.
	 * @return array WordPress author ID.
	 */
	private function map_authors( array $authors ): array {
		$all_authors  = $this->load_authors();
		$post_authors = [];

		foreach ( $authors as $author ) {
			if ( array_key_exists( $author, $all_authors ) ) {
				$post_authors[ $author ] = (int) $all_authors[ $author ];
			}
		}

		return $post_authors;
	}

	/**
	 * Maps Foundation categories to WordPress categories.
	 *
	 * @param array $categories Foundation categories.
	 * @return array WordPress category IDs.
	 */
	private function map_categories( array $categories ): array {
		$all_categories  = $this->load_taxonomies( Taxonomy::UNIQUE_CATEGORY_IDENTIFIER_META_KEY );
		$post_categories = [];

		foreach ( $categories as $category ) {
			if ( array_key_exists( $category, $all_categories ) ) {
				$post_categories[ $category ] = (int) $all_categories[ $category ];
			}
		}

		return $post_categories;
	}

	/**
	 * Loads authors from the database.
	 *
	 * @return array Authors.
	 */
	private function load_authors(): array {
		global $wpdb;

		$authors = [];

		// @phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
		$user_meta = $wpdb->get_results(
			$wpdb->prepare(
				"SELECT user_id, meta_value FROM {$wpdb->usermeta} WHERE meta_key = %s",
				[ UsersHelper::UNIQUE_IDENTIFIER_META_KEY ]
			)
		);

		foreach ( $user_meta as $user_meta_item ) {
			$authors[ $user_meta_item->meta_value ] = $user_meta_item->user_id;
		}

		return $authors;
	}

	/**
	 * Loads categories from the database.
	 *
	 * @param string $taxonomy_identifier_meta_key Taxonomy identifier meta key.
	 *
	 * @return array Categories.
	 */
	private function load_taxonomies( string $taxonomy_identifier_meta_key ): array {
		global $wpdb;

		$categories = [];

		// @phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
		$term_meta = $wpdb->get_results(
			$wpdb->prepare(
				"SELECT term_id, meta_value FROM {$wpdb->termmeta} WHERE meta_key = %s",
				[ $taxonomy_identifier_meta_key ]
			)
		);

		foreach ( $term_meta as $term_meta_item ) {
			$categories[ $term_meta_item->meta_value ] = $term_meta_item->term_id;
		}

		return $categories;
	}
