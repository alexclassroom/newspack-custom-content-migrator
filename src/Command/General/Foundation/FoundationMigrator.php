	/**
	 * Migrates Foundation posts received from their export.
	 * Callable for 'newspack-content-migrator foundation-migrate-posts' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_migrate_posts( array $args, array $assoc_args ): void {
		$next_time = microtime( true );

		global $wpdb;

		$logger     = MultiLog::get_cli_and_file_logger( __FUNCTION__ );
		$csv_writer = new CsvWriter( __FUNCTION__ . '.csv' );
		$csv_writer->set_header( [ 'oid', 'post_id', 'old_url', 'new_url' ] );

		$post_json_file  = $assoc_args['post-json-file'];
		$image_json_file = $assoc_args['image-json-file'];
		$embed_json_file = $assoc_args['embed-json-file'];
		$audio_json_file = $assoc_args['audio-json-file'];
		$pdf_json_file   = $assoc_args['pdf-json-file'];

		$raw_posts = $this->json_iterator->items( $post_json_file );

		$logger->info( sprintf( '%s took %s seconds', 'load files', round( microtime( true ) - $next_time, 2 ) ) );
		$next_time = microtime( true );

		$migrated_posts = [];

		foreach ( $raw_posts as $post ) {
			$mapped_authors    = $this->map_authors( $post->authors );
			$mapped_categories = $this->map_categories( $post->categories );
			$mapped_topics     = $this->map_categories( $post->topics );
			$post_categories   = array_values( array_merge( $mapped_categories, $mapped_topics ) );

			$logger->info( sprintf( '%s took %s seconds', 'map authors/categories', round( microtime( true ) - $next_time, 2 ) ) );
			$next_time = microtime( true );

			// Check if the post has non migrated authors.
			if ( count( $mapped_authors ) !== count( array_unique( $post->authors ) ) ) {
				$logger->error( sprintf( 'Skipping post %d because it has non migrated authors: %s', $post->oid, implode( ', ', array_diff( $post->authors, array_keys( $mapped_authors ) ) ) ) );
				// continue;
			}

			// Check if the post has non migrated categories.
			if ( count( $mapped_categories ) !== count( array_unique( $post->categories ) ) ) {
				$logger->error( sprintf( 'Post %d has non migrated categories: %s', $post->oid, implode( ', ', array_diff( $post->categories, array_keys( $post_categories ) ) ) ) );
			}

			// Check if the post has non migrated topics.
			if ( count( $mapped_topics ) !== count( array_unique( $post->topics ) ) ) {
				$logger->error( sprintf( 'Post %d has non migrated topics: %s', $post->oid, implode( ', ', array_diff( $post->topics, array_keys( $mapped_topics ) ) ) ) );
			}

			$release_date = new \DateTime( $post->releaseDate );
			$updated_date = new \DateTime( $post->updateDate );

			$post_data = [
				'post_type'         => 'post',
				'post_title'        => $post->headline,
				'post_name'         => $post->basename . '-' . $post->oid,
				'post_status'       => $this->map_post_status( $post->status ),
				'post_date'         => $release_date->format( 'Y-m-d H:i:s' ),
				'post_date_gmt'     => $release_date->setTimezone( new \DateTimeZone( 'UTC' ) )->format( 'Y-m-d H:i:s' ),
				'post_modified'     => $updated_date->format( 'Y-m-d H:i:s' ),
				'post_modified_gmt' => $updated_date->setTimezone( new \DateTimeZone( 'UTC' ) )->format( 'Y-m-d H:i:s' ),
				'post_content'      => $post->body,
				'post_category'     => $post_categories,
				'tags_input'        => $post->tags,
			];

			$logger->info( sprintf( '%s took %s seconds', 'generate post initial data', round( microtime( true ) - $next_time, 2 ) ) );
			$next_time        = microtime( true );
			$migrated_post_id = Posts::create_or_get_post( $post_data, $post->oid );
			$logger->info( sprintf( '%s took %s seconds', 'create post', round( microtime( true ) - $next_time, 2 ) ) );
			$next_time = microtime( true );

			if ( is_wp_error( $migrated_post_id ) ) {
				$logger->error( sprintf( 'Error migrating post %d: %s', $post->oid, $migrated_post_id->get_error_message() ) );
				continue;
			}

			// Assign contributors.
			GuestContributorsHelper::assign_contributors_to_post( $migrated_post_id, array_values( $mapped_authors ) );

			// Migrate images tray and featured image.
			$migrated_images = $this->migrate_images_tray_and_featured_image( $migrated_post_id, $post->imageLinks, $image_json_file );
			$logger->info( sprintf( '%s took %s seconds', 'migrate images tray and featured image', round( microtime( true ) - $next_time, 2 ) ) );
			$next_time = microtime( true );

			// Migrate post content.
			$updated_content = $this->generate_post_content( $migrated_post_id, $post, $migrated_images, $embed_json_file, $audio_json_file, $pdf_json_file );
			$logger->info( sprintf( '%s took %s seconds', 'generate post content', round( microtime( true ) - $next_time, 2 ) ) );
			$next_time = microtime( true );

			if ( $updated_content !== $post->body ) {
				// @phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
				$wpdb->update(
					$wpdb->posts,
					[ 'post_content' => $updated_content ],
					[ 'ID' => $migrated_post_id ]
				);
				$logger->info( sprintf( '%s took %s seconds', 'update post content', round( microtime( true ) - $next_time, 2 ) ) );
				$next_time = microtime( true );

				// If the first block is an image, hide the featured image.
				$content_blocks = parse_blocks( $updated_content );
				if ( isset( $content_blocks[0]['blockName'] ) && 'core/image' === $content_blocks[0]['blockName'] ) {
					update_post_meta( $migrated_post_id, 'newspack_featured_image_position', 'hidden' );
				}
			}

			// Setting the post's primary category.
			if ( ! empty( $post->primaryCategory ) ) {
				if ( ! array_key_exists( $post->primaryCategory, $mapped_categories ) ) {
					$logger->error( sprintf( 'Post %d has non migrated primary category: %s', $post->oid, $post->primaryCategory ) );
				} else {
					$primary_category_id = $mapped_categories[ $post->primaryCategory ];
					update_post_meta( $migrated_post_id, '_yoast_wpseo_primary_category', $primary_category_id );
				}
			}

			// Setting post meta.
			update_post_meta( $migrated_post_id, 'foundation_post_transfer', $post->transfer );
			update_post_meta( $migrated_post_id, 'foundation_post_source', $post->source );

			$migrated_posts[ $post->oid ] = $migrated_post_id;

			$csv_writer->put( [ $post->oid, $migrated_post_id, 'https://www.okgazette.com' . $post->permalink, get_permalink( $migrated_post_id ) ] );

			$logger->info( sprintf( 'Migrated post %d with ID %d', $post->oid, $migrated_post_id ) );
			$logger->info( sprintf( '%s took %s seconds', 'migrate post', round( microtime( true ) - $next_time, 2 ) ) );
			$logger->info( '+============================+' );
			$next_time = microtime( true );
		}

		$csv_writer->close();
	}

	/**
	 * Strips container divs robustly.
	 *
	 * @param string $html The HTML content to process.
	 * @return string The processed HTML content.
	 */
	private function strip_container_div_robust( string $html ): string {
		// Trim whitespace.
		$html = trim( $html );

		// Keep processing until no more attribute-less divs are found.
		$previous_length = 0;
		$current_length  = strlen( $html );
		while ( $current_length !== $previous_length ) {
			$previous_length = $current_length;
			$html            = $this->strip_attribute_less_divs( $html );
			$current_length  = strlen( $html );
		}

		return $html;
	}

	/**
	 * Helper function to strip one level of attribute-less divs.
	 *
	 * @param string $html The HTML content to process.
	 * @return string The processed HTML content.
	 */
	private function strip_attribute_less_divs( string $html ): string {
		// Use regex to find and replace attribute-less divs.
		// This pattern matches <div>content</div> where div has no attributes.
		$pattern = '/<div(?:\s+[^>]*)?>(.*?)<\/div>/s';

		// Keep replacing until no more matches.
		$previous_html = '';
		while ( $html !== $previous_html ) {
			$previous_html = $html;
			$html          = preg_replace_callback(
				$pattern,
				function ( $matches ) {
					// Check if the div tag has attributes.
					$div_tag         = $matches[0];
					$div_start       = strpos( $div_tag, '<div' );
					$div_end         = strpos( $div_tag, '>', $div_start );
					$div_tag_content = substr( $div_tag, $div_start, $div_end - $div_start + 1 );

					// If div has attributes (like class, id, style, etc.), keep it.
					if ( preg_match( '/<div\s+[^>]*>/', $div_tag_content ) ) {
						return $matches[0]; // Return unchanged.
					}

					// If div has no attributes, return just the content.
					return $matches[1];
				},
				$html
			);
		}

		return $html;
	}

	/**
	 * Generates post content.
	 *
	 * @param int    $post_id   Post ID.
	 * @param object $post Foundation post.
	 * @param array  $migrated_images Migrated images.
	 * @param string $embed_json_file Raw embeds file.
	 * @param string $audio_json_file Raw audios file.
	 * @param string $pdf_json_file   Raw PDFs file.
	 *
	 * @return string Post content.
	 */
	private function generate_post_content( int $post_id, object $post, array $migrated_images, string $embed_json_file, string $audio_json_file, string $pdf_json_file ): string {
		// TODO: Remove logger.
		$logger  = MultiLog::get_cli_and_file_logger( __FUNCTION__ );
		$content = $this->strip_container_div_robust( $post->body );

		// Migrate info box.
		$content = $this->migrate_info_box( $post->oid, $content, $post->infoBoxTitle, $post->infoBoxText, $post->infoBoxPosition );

		// Migrate images.
		$content = $this->migrate_images_markers( $post->oid, $content, $migrated_images, $post->imageLinks );

		// Migrate pullquote.
		if ( ! empty( $post->pullquotes ) ) {
			$content = $this->migrate_pullquote_markers( $post->oid, $content, $post->pullquotes );
		}

		// Migrate slideshow.
		if ( ! empty( $post->slideshow ) ) {
			echo 1;
			// TODO: Migrate slideshow.
		}

		// Migrate embed.
		if ( ! empty( $post->embed ) ) {
			$logger->info( sprintf( 'Migrating embeds for post %s', $post->oid ) );
			$content = $this->migrate_embed_markers( $post->oid, $content, $embed_json_file, $post->embed );
		}

		// Migrate audio.
		if ( ! empty( $post->audio ) ) {
			$logger->info( sprintf( 'Migrating audio for post %s', $post->oid ) );
			$content = $this->migrate_audio_markers( $post->oid, $post_id, $content, $audio_json_file, $post->audio );
		}

		// Migrate pdf.
		if ( ! empty( $post->pdf ) ) {
			$logger->info( sprintf( 'Migrating PDFs for post %s', $post->oid ) );
			$content = $this->migrate_pdf_markers( $post->oid, $post_id, $content, $pdf_json_file, $post->pdf );
		}

		return $content;
	}

	/**
	 * Migrate info box.
	 *
	 * @param string $post_oid Post OID.
	 * @param string $content Post content.
	 * @param string $info_box_title Info box title.
	 * @param string $info_box_text Info box text.
	 * @param string $info_box_position Info box position.
	 *
	 * @return string Post content with info box.
	 */
	private function migrate_info_box( string $post_oid, string $content, string $info_box_title, string $info_box_text, string $info_box_position ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		if ( ! empty( $info_box_title ) && ! empty( $info_box_text ) && ! empty( $info_box_position ) ) {
			$info_box_block = serialize_block(
				$this->gutenberg_block_generator->get_group_constrained(
					[ $this->gutenberg_block_generator->get_html( $info_box_title . $info_box_text ) ],
					[ 'newspack-embed-info-box', 'alignright' ],
					[ 'align' => 'right' ]
				)
			);

			switch ( $info_box_position ) {
				case 'top':
					return $info_box_block . $content;
				case 'bottom':
					return $content . $info_box_block;
				default:
					$logger->warning( sprintf( 'Info box position %s not supported for post %s', $info_box_position, $post_oid ) );
					return $content;
			}
		}

		return $content;
	}

	/**
	 * Migrate images tray and featured image.
	 *
	 * The featured image is the image with "Teaser" placement. The "first" image is also the default Teaser if a Teaser isn't set.
	 *
	 * @param int    $post_id      Post ID.
	 * @param array  $post_image_oids  Post image OIDs.
	 * @param string $raw_images_file Raw images file.
	 *
	 * @return array Migrated images. A key-value pair of post image OID and an array with the raw image data and the attachment ID.
	 */
	private function migrate_images_tray_and_featured_image( int $post_id, array $post_image_oids, string $raw_images_file ): array {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		if ( empty( $post_image_oids ) ) {
			return [];
		}

		$migrated_images           = [];
		$possible_teaser_image_ids = [];

		foreach ( $post_image_oids as $post_image_oid ) {
			$possible_raw_images = iterator_to_array( $this->json_iterator->filtered_items( $raw_images_file, 'oid', $post_image_oid ) );

			if ( 1 === count( $possible_raw_images ) ) {
				$raw_image     = $possible_raw_images[0];
				$attachment_id = $this->migrate_raw_attachment( $raw_image, $post_id );

				if ( is_wp_error( $attachment_id ) ) {
					$logger->error( sprintf( 'Error migrating image %s for post %s: %s', $post_image_oid, $post_id, $attachment_id->get_error_message() ) );
					continue;
				}

				$migrated_images[ $post_image_oid ] = [
					...(array) $raw_image,
					'attachment_id' => $attachment_id,
				];

				if ( isset( $raw_image->placements ) && in_array( 'teaser', $raw_image->placements, true ) ) {
					$possible_teaser_image_ids[] = $attachment_id;
				}
			} else {
				$logger->warning( sprintf( 'Image %s not found in raw images for post %s', $post_image_oid, $post_id ) );
			}
		}

		// Warn if there are multiple teaser images.
		if ( count( $possible_teaser_image_ids ) > 1 ) {
			$logger->warning( sprintf( 'Post %s has multiple teaser images: %s', $post_id, implode( ', ', $possible_teaser_image_ids ) ) );
		}

		// Set the featured image.
		if ( ! empty( $possible_teaser_image_ids ) ) {
			set_post_thumbnail( $post_id, $possible_teaser_image_ids[0] );
		} elseif ( ! empty( $migrated_images ) ) {
			set_post_thumbnail( $post_id, current( $migrated_images ) );
		}

		return $migrated_images;
	}

	/**
	 * Migrate images markers.
	 *
	 * Image markers in the content are in the format: [image-N] where N is a 1-based index.
	 * For example: [image-1] refers to the first image, [image-2] to the second, etc.
	 * This method converts these 1-based indices to 0-based indices for array access.
	 *
	 * @param string $post_oid     Post OID.
	 * @param string $content      Post content.
	 * @param array  $migrated_images   Migrated images. A key-value pair of post image OID and an array with the raw image data and the attachment ID.
	 * @param array  $post_image_oids  Post image OIDs. A 0-based indexed array.
	 *
	 * @return string Post content with image markers replaced by Gutenberg blocks.
	 */
	private function migrate_images_markers( string $post_oid, string $content, array $migrated_images, array $post_image_oids ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$content = preg_replace_callback(
			'/\[image-(\d+)\]/',
			function ( $matches ) use ( $post_oid, $migrated_images, $logger, $post_image_oids ) {
				$image_index = (int) $matches[1] - 1; // Convert to 0-based index.
				if ( ! isset( $migrated_images[ $post_image_oids[ $image_index ] ] ) ) {
					$logger->warning( sprintf( 'Image %d not found in post images for post %s', (int) $matches[1], $post_oid ) );
					return $matches[0];
				}
				$raw_image = $migrated_images[ $post_image_oids[ $image_index ] ];

				$attachment_post = get_post( $raw_image['attachment_id'] );

				if ( ! $attachment_post ) {
					$logger->warning( sprintf( 'Attachment post %d not found for image %d in post %s', $raw_image['attachment_id'], (int) $matches[1], $post_oid ) );
					return $matches[0];
				}

				$classes = '';
				if ( ! empty( $raw_image['alignment'] ) ) {
					$classes = 'align' . strtolower( $raw_image['alignment'] );
				}

				return serialize_block( $this->gutenberg_block_generator->get_image( $attachment_post, 'full', true, $classes, strtolower( $raw_image['alignment'] ), $raw_image['destinationURL'] ) );
			},
			$content
		);

		return $content;
	}

	/**
	 * Migrate pullquote markers.
	 *
	 * Pullquote markers in the content are in the format: [pullquote-N] where N is a 1-based index.
	 * For example: [pullquote-1-center] refers to the first pullquote, [pullquote-2] to the second, etc.
	 * This method converts these 1-based indices to 0-based indices for array access.
	 *
	 * @param string $post_oid        Post OID.
	 * @param string $content         Post content.
	 * @param array  $post_pullquotes Post pullquotes array (0-based indexed).
	 *
	 * @return string Post content with pullquote markers replaced by their content.
	 */
	private function migrate_pullquote_markers( string $post_oid, string $content, array $post_pullquotes ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$content = preg_replace_callback(
			'/\[pullquote-(\d+)-(\w+)\]/',
			function ( $matches ) use ( $post_oid, $logger, $post_pullquotes ) {
				$pullquote_index = (int) $matches[1] - 1; // Convert to 0-based index.
				if ( ! isset( $post_pullquotes[ $pullquote_index ] ) ) {
					$logger->warning( sprintf( 'Pullquote %d not found in post pullquotes for post %s', (int) $matches[1], $post_oid ) );
					return $matches[0];
				}
				return serialize_block( $this->gutenberg_block_generator->get_quote( $post_pullquotes[ $pullquote_index ] ) );
			},
			$content
		);

		return $content;
	}

	/**
	 * Migrate embed markers.
	 *
	 * Embed markers in the content are in the format: [embed-N] where N is a 1-based index.
	 * For example: [embed-1] refers to the first embed, [embed-2] to the second, etc.
	 * This method converts these 1-based indices to 0-based indices for array access.
	 *
	 * @param string $post_oid    Post OID.
	 * @param string $content     Post content.
	 * @param string $embed_json_file Raw embeds file.
	 * @param array  $post_embeds Post embeds array (0-based indexed).
	 *
	 * @return string Post content with embed markers replaced by Gutenberg blocks.
	 */
	private function migrate_embed_markers( string $post_oid, string $content, string $embed_json_file, array $post_embeds ): string {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$content = preg_replace_callback(
			'/\[embed-(\d+)\]/',
			function ( $matches ) use ( $post_oid, $embed_json_file, $logger, $post_embeds ) {
				$embed_index = (int) $matches[1] - 1; // Convert to 0-based index.
				if ( ! isset( $post_embeds[ $embed_index ] ) ) {
					$logger->warning( sprintf( 'Embed %d not found in post embeds for post %s', (int) $matches[1], $post_oid ) );
					return $matches[0];
				}
				$embed_id            = $post_embeds[ $embed_index ];
				$possible_raw_embeds = iterator_to_array( $this->json_iterator->filtered_items( $embed_json_file, 'oid', $embed_id ) );

				if ( 1 === count( $possible_raw_embeds ) ) {
					$raw_embed      = $possible_raw_embeds[0];
					$migrated_embed = $this->migrate_raw_embed( $raw_embed );

					if ( is_wp_error( $migrated_embed ) ) {
						$logger->error( sprintf( 'Error migrating embed %s for post %s: %s', $matches[1], $post_oid, $migrated_embed->get_error_message() ) );
						return $matches[0];
					}

					return $migrated_embed;
				}

				$logger->warning( sprintf( 'Embed %d not found in raw embeds for post %s', $matches[1], $post_oid ) );
				return $matches[0];
			},
			$content
		);

		return $content;
	}

