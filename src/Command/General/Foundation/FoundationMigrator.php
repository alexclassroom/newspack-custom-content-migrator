	 * Callable for 'newspack-content-migrator foundation-migrate-users' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_migrate_users( array $args, array $assoc_args ): void {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$wp_author_json_file         = $assoc_args['wp-author-json-file'];
		$wp_contributor_json_file    = $assoc_args['wp-contributor-json-file'];
		$wp_editor_json_file         = $assoc_args['wp-editor-json-file'];
		$wp_comment_author_json_file = $assoc_args['wp-comment-author-json-file'];

		$logger->info( sprintf( 'Migrating users from %s, %s, %s and %s', $wp_author_json_file, $wp_contributor_json_file, $wp_editor_json_file, $wp_comment_author_json_file ) );

		$raw_authors         = $this->json_iterator->items( $wp_author_json_file );
		$raw_contributors    = $this->json_iterator->items( $wp_contributor_json_file );
		$raw_editors         = $this->json_iterator->items( $wp_editor_json_file );
		$raw_comment_authors = $this->json_iterator->items( $wp_comment_author_json_file );

		$migrated_authors         = [];
		$migrated_contributors    = [];
		$migrated_editors         = [];
		$migrated_comment_authors = [];

		// Migrate comment authors.
		foreach ( $raw_comment_authors as $comment_author ) {
			$migrated_comment_author_id                       = $this->migrate_to_wp_user( $comment_author, 'subscriber', $logger );
			$migrated_comment_authors[ $comment_author->oid ] = $migrated_comment_author_id;
			$logger->info( sprintf( 'Migrated comment author %s with ID %d', $comment_author->oid, $migrated_comment_author_id ) );
		}

		// Migrate authors.
		foreach ( $raw_authors as $author ) {
			$migrated_author_id = $this->migrate_to_wp_user( $author, 'author', $logger );

			$migrated_authors[ $author->oid ] = $migrated_author_id;
			$logger->info( sprintf( 'Migrated author %s with ID %d', $author->oid, $migrated_author_id ) );
		}

		// Migrate contributors.
		foreach ( $raw_contributors as $contributor ) {
			$contributor_data     = [
				'user_login'   => $contributor->username,
				'user_email'   => $contributor->email,
				'display_name' => $this->clean_display_name( $contributor->displayName ),
				'user_url'     => $contributor->website,
				'meta_input'   => [
					'description' => $contributor->bio,
					'facebook'    => $contributor->facebookUrl,
					'instagram'   => $contributor->instagramUrl,
					'linkedin'    => $contributor->linkedinUrl,
					'twitter'     => $contributor->twitterUrl,
					'youtube'     => $contributor->youtubeUrl,
					'bluesky'     => $contributor->blueskyUrl,
				],
			];
			$migrated_contributor = GuestContributorsHelper::create_or_get_contributor( $contributor_data, $contributor->oid );

			if ( is_wp_error( $migrated_contributor ) ) {
				$logger->error( sprintf( 'Error migrating contributor %s: %s', $contributor->oid, $migrated_contributor->get_error_message() ) );
				continue;
			}

			// Upload and set avatar if available.
			if ( isset( $contributor->image ) && ! empty( $contributor->image ) ) {
				$avatar_id = Attachments::import_external_file( $contributor->image );
				if ( is_wp_error( $avatar_id ) ) {
					$logger->error( sprintf( 'Error importing avatar for contributor %s (%s): %s', $contributor->oid, $contributor->image, $avatar_id->get_error_message() ) );
				} else {
					$this->simple_local_avatars->assign_avatar( $migrated_contributor->ID, $avatar_id );
				}
			}

			$migrated_contributors[ $contributor->oid ] = $migrated_contributor->ID;
			$logger->info( sprintf( 'Migrated contributor %s with ID %d', $contributor->oid, $migrated_contributor->ID ) );
		}

		// Migrate editors.
		foreach ( $raw_editors as $editor ) {
			$migrated_editor_id = $this->migrate_to_wp_user( $editor, 'editor', $logger );

			$migrated_editors[ $editor->oid ] = $migrated_editor_id;
			$logger->info( sprintf( 'Migrated editor %s with ID %d', $editor->oid, $migrated_editor_id ) );
		}

		$logger->info( sprintf( 'Migrated %d authors, %d contributors, %d editors and %d subscribers.', count( $migrated_authors ), count( $migrated_contributors ), count( $migrated_editors ), count( $migrated_comment_authors ) ) );
		$logger->info( sprintf( 'Check the log file for migration details: %s', __FUNCTION__ . '.log' ) );
	}

	/**
	 * Migrates Foundation posts received from their export.
	 * Callable for 'newspack-content-migrator foundation-migrate-posts' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_migrate_posts( array $args, array $assoc_args ): void {
		global $wpdb;

		$logger     = MultiLog::get_cli_and_file_logger( __FUNCTION__ );
		$csv_writer = new CsvWriter( __FUNCTION__ . '.csv' );
		$csv_writer->set_header( [ 'oid', 'post_id', 'old_url', 'new_url' ] );

		$publisher_domain       = $assoc_args['publisher-domain'];
		$post_json_file         = $assoc_args['post-json-file'];
		$image_json_file        = $assoc_args['image-json-file'];
		$embed_json_file        = $assoc_args['embed-json-file'];
		$audio_json_file        = $assoc_args['audio-json-file'];
		$pdf_json_file          = $assoc_args['pdf-json-file'];
		$slideshow_json_file    = $assoc_args['slideshow-json-file'];
		$start_from             = $assoc_args['start-from'] ?? 0;
		$end_at                 = $assoc_args['end-at'] ?? 0;
		$update_content         = $assoc_args['update-content'] ?? false;
		$oid_to_migrate         = isset( $assoc_args['oid-to-migrate'] ) ? explode( ',', $assoc_args['oid-to-migrate'] ) : [];
		$this->media_local_path = $assoc_args['media-local-path'] ?? '';

		$raw_posts               = $this->json_iterator->items( $post_json_file );
		$all_migrated_posts_oids = array_keys( $this->load_posts() );

		$migrated_posts = [];
		$skipped_posts  = [];

		foreach ( $raw_posts as $index => $post ) {
			if ( $index < ( $start_from - 1 ) || ( $end_at > 0 && $index >= $end_at ) ) {
				continue;
			}

			if ( ! empty( $oid_to_migrate ) && ! in_array( $post->oid, $oid_to_migrate ) ) {
				continue;
			}

			if ( ! $update_content && in_array( $post->oid, $all_migrated_posts_oids ) ) {
				$skipped_posts[] = $post->oid;
				$logger->info( sprintf( '[%d] Skipping post %d because it has already been migrated', $index + 1, $post->oid ) );
				continue;
			}

			$mapped_authors    = $this->map_authors( $post->authors );
			$mapped_categories = $this->map_categories( $post->categories );
			$mapped_topics     = $this->map_categories( $post->topics );
			$post_categories   = array_values( array_merge( $mapped_categories, $mapped_topics ) );

			// Check if the post has non migrated authors.
			if ( count( $mapped_authors ) !== count( array_unique( $post->authors ) ) ) {
				$logger->error( sprintf( '[%d] Skipping post %d because it has non migrated authors: %s', $index + 1, $post->oid, implode( ', ', array_diff( $post->authors, array_keys( $mapped_authors ) ) ) ) );
				continue;
			}

			// Check if the post has non migrated categories.
			if ( count( $mapped_categories ) !== count( array_unique( $post->categories ) ) ) {
				$logger->error( sprintf( 'Post %d has non migrated categories: %s', $post->oid, implode( ', ', array_diff( $post->categories, array_keys( $post_categories ) ) ) ) );
			}

			// Check if the post has non migrated topics.
			if ( count( $mapped_topics ) !== count( array_unique( $post->topics ) ) ) {
				$logger->error( sprintf( 'Post %d has non migrated topics: %s', $post->oid, implode( ', ', array_diff( $post->topics, array_keys( $mapped_topics ) ) ) ) );
			}

			$release_date = new \DateTime( $post->releaseDate );
			$updated_date = new \DateTime( $post->updateDate );

			$post_data = [
				'post_type'         => 'post',
				'post_title'        => wp_strip_all_tags( preg_replace( '/&#(?:10|13);/', '', $post->headline ) ),
				'post_name'         => $post->basename . '-' . $post->oid,
				'post_excerpt'      => $post->summary,
				'post_status'       => $this->map_post_status( $post->status ),
				'post_date'         => $release_date->format( 'Y-m-d H:i:s' ),
				'post_date_gmt'     => $release_date->setTimezone( new \DateTimeZone( 'UTC' ) )->format( 'Y-m-d H:i:s' ),
				'post_modified'     => $updated_date->format( 'Y-m-d H:i:s' ),
				'post_modified_gmt' => $updated_date->setTimezone( new \DateTimeZone( 'UTC' ) )->format( 'Y-m-d H:i:s' ),
				'post_content'      => $post->body,
				'post_category'     => $post_categories,
				'tags_input'        => $post->tags ?? [],
				'comment_status'    => in_array( $post->commentStatus, [ 'open', 'members only' ] ) ? 'open' : 'close',
			];

			$migrated_post_id = Posts::create_or_get_post( $post_data, $post->oid );

			if ( is_wp_error( $migrated_post_id ) ) {
				$logger->error( sprintf( 'Error migrating post %d: %s', $post->oid, $migrated_post_id->get_error_message() ) );
				continue;
			}

			// Assign contributors.
			GuestContributorsHelper::assign_contributors_to_post( $migrated_post_id, array_values( $mapped_authors ) );

			// Set custom byline if the credit type is different than 'by'.
			if ( 'by' !== trim( strtolower( $post->creditType ) ) ) {
				$authors_byline_parts = array_values(
					array_filter(
						array_map(
							function ( $author_id ) {
								$wp_user = get_user_by( 'ID', $author_id );
								return $wp_user ? "[Author id=$author_id]{$wp_user->display_name}[/Author]" : '';
							},
							array_values( $mapped_authors )
						)
					)
				);

				$byline_authors = $post->creditType . ' ' . $this->format_natural_language_list( $authors_byline_parts );
				update_post_meta( $migrated_post_id, '_newspack_byline_active', true );
				update_post_meta( $migrated_post_id, '_newspack_byline', $byline_authors );
			}

			// Migrate images tray and featured image.
			$time            = microtime( true );
			$migrated_images = $this->migrate_images_tray_and_featured_image( $migrated_post_id, $post->imageLinks, $image_json_file, $post->images ?? [], $update_content );
			$logger->info( sprintf( 'Migrated images tray and featured image in %s.02 seconds', microtime( true ) - $time ) );

			// Migrate post content.
			$updated_content = $this->generate_post_content( $migrated_post_id, $post, $migrated_images, $embed_json_file, $audio_json_file, $pdf_json_file, $slideshow_json_file, $update_content );

			if ( $updated_content !== $post->body ) {
				// @phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
				$wpdb->update(
					$wpdb->posts,
					[ 'post_content' => $updated_content ],
					[ 'ID' => $migrated_post_id ]
				);

				// If the first block is an image, hide the featured image.
				$content_blocks = parse_blocks( $updated_content );
				if ( isset( $content_blocks[0]['blockName'] ) && in_array( $content_blocks[0]['blockName'], [ 'core/image', 'core/gallery', 'core/embed', 'jetpack/slideshow' ], true ) ) {
					update_post_meta( $migrated_post_id, 'newspack_featured_image_position', 'hidden' );
				}

				// Or if the first block is a slideshow with the custom classname 'fdn-embedded-gallery-content-loop'.
				if ( isset( $content_blocks[0]['blockName'] ) && 'newspack-blocks/homepage-articles' === $content_blocks[0]['blockName'] && isset( $content_blocks[0]['attrs']['className'] ) && 'fdn-embedded-gallery-content-loop' === $content_blocks[0]['attrs']['className'] ) {
					update_post_meta( $migrated_post_id, 'newspack_featured_image_position', 'hidden' );
				}

				// Or if the featured image is in the content.
				$featured_image_id = get_post_thumbnail_id( $migrated_post_id );
				if ( $featured_image_id ) {
					$featured_image_url = wp_get_attachment_image_src( $featured_image_id, 'full' )[0];
					// Get the featured image filename.
					$featured_image_filename = basename( $featured_image_url );
					if ( strpos( $updated_content, $featured_image_filename ) !== false ) {
						update_post_meta( $migrated_post_id, 'newspack_featured_image_position', 'hidden' );
					}
				}
			}

			// Setting the post's primary category.
			if ( ! empty( $post->primaryCategory ) ) {
				if ( ! array_key_exists( $post->primaryCategory, $mapped_categories ) ) {
					$logger->error( sprintf( 'Post %d has non migrated primary category: %s', $post->oid, $post->primaryCategory ) );
				} else {
					$primary_category_id = $mapped_categories[ $post->primaryCategory ];
					update_post_meta( $migrated_post_id, '_yoast_wpseo_primary_category', $primary_category_id );
				}
			}

			// Setting post meta.
			update_post_meta( $migrated_post_id, 'foundation_post_transfer', $post->transfer );
			update_post_meta( $migrated_post_id, 'foundation_post_source', $post->source );

			// Seven Days have their subtitles in the description field.
			if ( str_contains( $publisher_domain, 'sevendaysvt.com' ) ) {
				update_post_meta( $migrated_post_id, 'newspack_post_subtitle', $post->description ?? '' );
			} else {
				update_post_meta( $migrated_post_id, 'newspack_post_subtitle', $post->subHeadline ?? '' );
			}

			// Setting the post's template.
			if ( isset( $post->layout ) && in_array( $post->layout, self::WIDE_LAYOUTS_LIST, true ) ) {
				update_post_meta( $migrated_post_id, '_wp_page_template', 'single-feature.php' );
				update_post_meta( $migrated_post_id, 'newspack_featured_image_position', 'above' );
			}

			// Since we regenerated the post content, we need to regenerate the post content for related posts.
			delete_post_meta( $migrated_post_id, self::MIGRATED_RELATED_POSTS_META_KEY );
			delete_post_meta( $migrated_post_id, self::MIGRATED_RELATED_SLIDESHOWS_META_KEY );

			// Migrate brand.
			if ( isset( $post->brand ) && ! empty( $post->brand ) ) {
				// Check if the brand term exists, if not create it.
				$brand_term = get_term_by( 'name', $post->brand, 'brand' );
				if ( ! $brand_term ) {
					$brand_term_result = wp_insert_term( $post->brand, 'brand' );
					if ( is_wp_error( $brand_term_result ) ) {
						$logger->error( sprintf( 'Error creating brand "%s": %s', $post->brand, $brand_term_result->get_error_message() ) );
					} else {
						$brand_term = get_term( $brand_term_result['term_id'], 'brand' );
						$logger->info( sprintf( 'Created brand "%s" with ID %d', $post->brand, $brand_term->term_id ) );
					}
				}

				// Set the brand term as a post meta.
				if ( $brand_term ) {
					wp_set_object_terms( $migrated_post_id, [ $brand_term->term_id ], 'brand' );
				}
			}

			$migrated_posts[ $post->oid ] = $migrated_post_id;

			$csv_writer->put( [ $post->oid, $migrated_post_id, 'https://' . $publisher_domain . $post->permalink, get_permalink( $migrated_post_id ) ] );

			// Make sure the update date didn't change.
			// @phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
			$wpdb->update(
				$wpdb->posts,
				[
					'post_modified'     => $updated_date->format( 'Y-m-d H:i:s' ),
					'post_modified_gmt' => $updated_date->setTimezone( new \DateTimeZone( 'UTC' ) )->format( 'Y-m-d H:i:s' ),
				],
				[ 'ID' => $migrated_post_id ]
			);

			$logger->info( sprintf( '[%d] Migrated post %d with ID %d', $index + 1, $post->oid, $migrated_post_id ) );
		}

		wp_cache_flush();
		$logger->info( sprintf( 'Skipped %d posts because they have already been migrated.', count( $skipped_posts ) ) );
		$logger->info( sprintf( 'Migrated %d posts.', count( $migrated_posts ) ) );
		$logger->info( sprintf( 'Check the log file for migration details: %s', __FUNCTION__ . '.log' ) );
		$logger->info( sprintf( 'Check the CSV file for migration details: %s', __FUNCTION__ . '.csv' ) );

		$csv_writer->close();
	}

