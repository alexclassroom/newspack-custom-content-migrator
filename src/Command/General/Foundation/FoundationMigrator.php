	/**
	 * Migrates Foundation taxonomies received from their export.
	 * Callable for 'newspack-content-migrator foundation-migrate-taxonomies' command.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 */
	public function cmd_migrate_taxonomies( array $args, array $assoc_args ): void {
		$logger = MultiLog::get_cli_and_file_logger( __FUNCTION__ );

		$category_json_file = $assoc_args['category-json-file'];

		$logger->info( sprintf( 'Migrating taxonomies from %s', $category_json_file ) );

		$raw_sections   = $this->json_iterator->filtered_items( $category_json_file, 'class', 'Section' );
		$raw_categories = $this->json_iterator->filtered_items( $category_json_file, 'class', 'Category' );
		$raw_tags       = $this->json_iterator->filtered_items( $category_json_file, 'class', 'Tag' );

		$migrated_sections   = [];
		$migrated_categories = [];
		$migrated_tags       = [];

		// Migrate sections (main categories).
		foreach ( $raw_sections as $section ) {
			$migrated_section = $this->taxonomy_logic->get_or_create_category(
				[
					'cat_name'             => $section->name,
					'category_description' => $section->description,
					'category_nicename'    => $section->id,
					'category_parent'      => 0,
				],
				$section->oid
			);

			if ( is_wp_error( $migrated_section ) ) {
				$logger->error( sprintf( 'Error migrating section %s: %s', $section->name, $migrated_section->get_error_message() ) );
				continue;
			}

			$migrated_sections[ $section->oid ] = $migrated_section;
			$logger->info( sprintf( 'Migrated section %s with ID %d', $section->name, $migrated_section ) );
		}

		// Migrate categories.
		foreach ( $raw_categories as $category ) {
			$parent_id = 0;
			if ( isset( $category->section ) ) {
				if ( isset( $migrated_sections[ $category->section ] ) ) {
					$parent_id = $migrated_sections[ $category->section ];
				} else {
					$logger->error( sprintf( 'Section %s not found', $category->section ) );
					continue;
				}
			}

			// TODO: Migrate category image as part of the category description.
			$migrated_category = $this->taxonomy_logic->get_or_create_category(
				[
					'cat_name'             => $category->name,
					'category_description' => $category->description,
					'category_nicename'    => $category->id,
					'category_parent'      => $parent_id,
				],
				$category->oid
			);

			if ( is_wp_error( $migrated_category ) ) {
				$logger->error( sprintf( 'Error migrating category %s: %s', $category->name, $migrated_category->get_error_message() ) );
				continue;
			}

			$migrated_categories[ $category->oid ] = $migrated_category;
			$logger->info( sprintf( 'Migrated category %s with ID %d', $category->name, $migrated_category ) );
		}

		// Migrate tags.
		foreach ( $raw_tags as $tag ) {
			// TODO: Migrate tags.
			$logger->info( sprintf( 'Migrating tags %s', $tag->name ) );
		}

		$logger->info( sprintf( 'Migrated %d sections, %d categories and %d tags', count( $migrated_sections ), count( $migrated_categories ), count( $migrated_tags ) ) );
	}

